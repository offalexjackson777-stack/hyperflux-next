from __future__ import annotations

from pathlib import Path
import sys
import unittest


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from hfxdev.atlas import load_repository_atlas
from hfxdev.documentation import load_document_catalog
from hfxdev.generators.generated_index import markdown as generated_index
from hfxdev.model import ModelError
from hfxdev.profiles import compiled_catalog
from hfxdev.render import _component_label
from hfxdev.generators.atlas import folder_readme, markdown
from hfxdev.testgraph import load_test_catalog, select_tests


class RepositoryAtlasTests(unittest.TestCase):
    def test_graph_covers_required_subsystems_with_unique_ownership(self) -> None:
        atlas = load_repository_atlas(ROOT)
        self.assertEqual(atlas.publication_state, "public-arch-release")
        self.assertIn("device-qualification-console", atlas.by_id)
        self.assertEqual(
            {node.category for node in atlas.nodes},
            {
                "architecture",
                "assurance",
                "runtime",
                "applications",
                "tooling",
                "delivery",
                "governance",
                "documentation",
            },
        )
        canonical_files = [
            path for node in atlas.nodes for path in node.canonical_files
        ]
        self.assertEqual(len(canonical_files), len(set(canonical_files)))

    def test_used_by_is_the_exact_dependency_inverse(self) -> None:
        atlas = load_repository_atlas(ROOT)
        for node in atlas.nodes:
            for dependency in node.depends_on:
                self.assertIn(node.id, atlas.used_by[dependency])
        self.assertEqual(set(atlas.used_by), set(atlas.by_id))

    def test_foundation_authorities_are_visible_in_the_atlas(self) -> None:
        atlas = load_repository_atlas(ROOT)
        self.assertIn(
            "runtime/local-companion.json",
            atlas.by_id["runtime-config"].canonical_files,
        )
        self.assertIn(
            "governance/licensing.json",
            atlas.by_id["governance"].canonical_files,
        )
        self.assertIn(
            "generated/public-readiness.json",
            atlas.by_id["documentation"].generated_files,
        )
        self.assertIn("tools/hfxdev/render.py", atlas.by_id["tooling"].canonical_files)

    def test_folder_readmes_expose_the_complete_contract(self) -> None:
        atlas = load_repository_atlas(ROOT)
        required = (
            "## Boundaries",
            "## Key Files",
            "## Verify",
        )
        for node in atlas.nodes:
            with self.subTest(node=node.id):
                rendered = folder_readme(atlas, node)
                for heading in required:
                    self.assertIn(heading, rendered)
                self.assertIn(node.purpose, rendered)
                self.assertIn("Generated by `./hfx generate`", rendered)

    def test_generated_terminology_uses_typed_labels_and_exact_snapshots(self) -> None:
        architecture = (ROOT / "docs" / "generated" / "architecture.md").read_text(
            encoding="utf-8"
        )
        self.assertIn('sdk["SDK"]', architecture)
        self.assertIn("### SDK\n", architecture)
        self.assertNotIn("Sdk", architecture)
        self.assertNotIn("non-authorizing", architecture)
        self.assertIn("are covered by both", architecture)
        with self.assertRaisesRegex(ModelError, "no display label"):
            _component_label("relay")
        knowledge = (ROOT / "docs" / "architecture" / "device-knowledge.md").read_text(
            encoding="utf-8"
        )
        self.assertNotIn("Today", knowledge)
        self.assertNotIn("mat snapshot", knowledge)
        apps = (ROOT / "apps" / "README.md").read_text(encoding="utf-8")
        self.assertTrue(apps.startswith("# Source-Only Applications\n"))
        atlas = load_repository_atlas(ROOT)
        for node in atlas.nodes:
            readme = ROOT / node.path / "README.md"
            if not readme.is_file() or node.id == "documentation":
                continue
            text = readme.read_text(encoding="utf-8")
            with self.subTest(readme=node.path):
                self.assertNotIn("Installed Applications", text)
                if "**Owns**" in text:
                    self.assertIn("**Owns**\n\n- ", text)
                    self.assertIn("**Does not own**\n\n- ", text)

    def test_generated_reference_index_lists_pages_and_defines_terms_once(self) -> None:
        catalog = load_document_catalog(ROOT)
        index_path = ROOT / "docs" / "generated" / "README.md"
        index = index_path.read_text(encoding="utf-8")
        self.assertEqual(index, generated_index(catalog, compiled_catalog(ROOT)))
        pages = sorted((ROOT / "docs" / "generated").glob("*.md"))
        for page in pages:
            if page.name == "README.md":
                continue
            with self.subTest(page=page.name):
                self.assertIn(f"]({page.name})", index)
                text = page.read_text(encoding="utf-8")
                for term in ("Receiver", "Mat", "Hard Edition", "Cloth Edition"):
                    self.assertNotIn(f"| {term} |", text)
        for term in ("Receiver", "Child", "Mat", "Hard Edition", "Cloth Edition", "Route"):
            self.assertEqual(index.count(f"| {term} |"), 1)

    def test_atlas_authority_describes_the_published_release(self) -> None:
        text = (ROOT / "architecture" / "repository-atlas.json").read_text(encoding="utf-8")
        for stale in (
            "remains a blocker",
            "remains pending",
            "publication remains disabled",
            "publication lock",
            "publication interlock",
            "software-only mission",
            "not a product release",
            "authorize",
        ):
            with self.subTest(stale=stale):
                self.assertNotIn(stale, text.lower())
        atlas = load_repository_atlas(ROOT)
        self.assertEqual(atlas.publication_state, "public-arch-release")
        self.assertIn(
            "Product releases are maintainer-operated, not published by workflows",
            atlas.by_id["governance"].public_contracts,
        )

    def test_generation_and_change_impact_are_deterministic(self) -> None:
        atlas = load_repository_atlas(ROOT)
        self.assertEqual(markdown(atlas), markdown(load_repository_atlas(ROOT)))
        for node in atlas.nodes:
            self.assertEqual(folder_readme(atlas, node), folder_readme(atlas, node))

    def test_atlas_source_change_selects_all_direct_contract_consumers(self) -> None:
        selection = select_tests(
            load_test_catalog(ROOT),
            "fast",
            ("architecture/repository-atlas.json",),
        )
        selected = {node.id for node in selection.nodes}
        self.assertLessEqual(
            {
                "schema-contracts",
                "repository-atlas-contracts",
                "generated-freshness",
                "repository-documentation-contracts",
                "python-unit",
            },
            selected,
        )


if __name__ == "__main__":
    unittest.main()
