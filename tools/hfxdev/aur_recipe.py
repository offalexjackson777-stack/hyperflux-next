@dataclass(frozen=True)
class AurAuthority:
    source_sha256: str
    source_name: str
    repository: str
    copyright: str
    makedepends: tuple[str, ...]
    options: tuple[str, ...]


@dataclass(frozen=True)
class UpstreamPin:
    id: str
    url: str
    commit: str
    checksum: str
    transform: dict[str, Any]


@dataclass(frozen=True)
class SourceReference:
    kind: str
    name: str
    commit: str
    url: str
    checksum: str


@dataclass(frozen=True)
class AurRecipe:
    mode: str
    version: str
    source: SourceReference
    upstreams: tuple[UpstreamPin, ...]
    validpgpkeys: tuple[str, ...]
    bound_paths: tuple[str, ...]
    disclosures: tuple[str, ...]
    files: dict[str, str]


def _exact_keys(value: Any, expected: set[str], label: str) -> dict[str, Any]:
    if not isinstance(value, dict) or set(value) != expected:
        raise ModelError(f"{label} has unexpected or missing fields")
    return value


def _text(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value or len(value) > 400:
        raise ModelError(f"{label} must be bounded text")
    if re.search(r"[\x00-\x1f\x7f]", value):
        raise ModelError(f"{label} contains a control character")
    return value


def load_aur_authority(root: Path) -> AurAuthority:
    path = root / AUTHORITY
    value = _exact_keys(
        load_json(path),
        {
            "$schema",
            "schema",
            "source",
            "packaging_license",
            "makedepends",
            "options",
            "options_rule",
        },
        "AUR recipe authority",
    )
    if value["$schema"] != SCHEMA_PATH or value["schema"] != SCHEMA:
        raise ModelError("unsupported AUR recipe authority schema")
    source = _exact_keys(
        value["source"],
        {"name", "repository", "publication_reference", "rule"},
        "AUR recipe source",
    )
    if not isinstance(source["name"], str) or not re.fullmatch(
        r"[a-z][a-z0-9-]{0,63}", source["name"]
    ):
        raise ModelError("AUR recipe source name is invalid")
    repository = source["repository"]
    if not isinstance(repository, str) or not re.fullmatch(
        r"https://[A-Za-z0-9./_-]+\.git", repository
    ):
        raise ModelError("AUR recipe source repository must be an https Git URL")
    if source["publication_reference"] != "signed-tag":
        raise ModelError("AUR recipe publication must reference a signed tag")
    _text(source["rule"], "AUR recipe source rule")
    licensing = _exact_keys(
        value["packaging_license"], {"spdx", "copyright", "rule"}, "AUR packaging license"
    )
    if licensing["spdx"] != "0BSD":
        raise ModelError("AUR packaging sources must be 0BSD")
    copyright_holder = _text(licensing["copyright"], "AUR packaging copyright")
    _text(licensing["rule"], "AUR packaging license rule")
    makedepends = value["makedepends"]
    if (
        not isinstance(makedepends, list)
        or not makedepends
        or any(not isinstance(item, str) or not PACKAGE_WORD.fullmatch(item) for item in makedepends)
        or len(set(makedepends)) != len(makedepends)
        or makedepends != sorted(makedepends)
    ):
        raise ModelError("AUR makedepends must be unique sorted package names")
    options = value["options"]
    if (
        not isinstance(options, list)
        or any(item not in ALLOWED_OPTIONS for item in options)
        or len(set(options)) != len(options)
    ):
        raise ModelError("AUR recipe options are not admitted")
    _text(value["options_rule"], "AUR recipe options rule")
    return AurAuthority(
        source_sha256=sha256_file(path),
        source_name=source["name"],
        repository=repository,
        copyright=copyright_holder,
        makedepends=tuple(makedepends),
        options=tuple(options),
    )


def _git(
    repository: Path,
    arguments: list[str],
    *,
    environment: Mapping[str, str] | None = None,
    input_bytes: bytes | None = None,
) -> subprocess.CompletedProcess[bytes]:
    try:
        return subprocess.run(
            ["git", "-c", "core.abbrev=no", "-C", str(repository), *arguments],
            check=False,
            input=input_bytes,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=600,
            env={**os.environ, **(environment or {}), "GIT_TERMINAL_PROMPT": "0", "LC_ALL": "C"},
        )
    except (OSError, subprocess.SubprocessError) as error:
        raise ModelError(f"cannot run git: {error}") from error


def _git_text(repository: Path, arguments: list[str], label: str) -> str:
    result = _git(repository, arguments)
    if result.returncode != 0:
        raise ModelError(f"{label}: git {' '.join(arguments)} failed")
    return result.stdout.decode("utf-8", "replace").strip()


def git_archive_sha256(repository: Path, reference: str) -> str:
    """The checksum makepkg computes for a `#tag=` or `#commit=` Git source."""

    result = _git(repository, ["archive", "--format", "tar", reference])
    if result.returncode != 0:
        raise ModelError(f"cannot archive {reference} from {repository.name}")
    return hashlib.sha256(result.stdout).hexdigest()


def _signed_tag(
    repository: Path,
    tag: str,
    fingerprint: str,
    environment: Mapping[str, str] | None,
) -> str:
    if not TAG_NAME.fullmatch(tag):
        raise ModelError("AUR source tag name is not admitted")
    reference = f"refs/tags/{tag}"
    if _git_text(repository, ["cat-file", "-t", reference], "AUR source tag") != "tag":
        raise ModelError(f"AUR source tag {tag} is lightweight; publication needs an annotated signed tag")
    body = _git(repository, ["cat-file", "tag", reference]).stdout
    if b"-----BEGIN PGP SIGNATURE-----" not in body:
        raise ModelError(f"AUR source tag {tag} is not signed")
    verified = _git(repository, ["verify-tag", "--raw", reference], environment=environment)
    signers = {
        line.split()[-1]
        for line in verified.stderr.decode("utf-8", "replace").splitlines()
        if line.startswith("[GNUPG:] VALIDSIG ")
    }
    if verified.returncode != 0 or signers != {fingerprint}:
        raise ModelError(f"AUR source tag {tag} is not signed by the project key {fingerprint}")
    return _git_text(repository, ["rev-parse", f"{reference}^{{commit}}"], "AUR source tag")


def _commit(repository: Path, commit: str) -> str:
    if not FULL_COMMIT.fullmatch(commit):
        raise ModelError("AUR source commit must be a full lowercase object name")
    if _git_text(repository, ["cat-file", "-t", commit], "AUR source commit") != "commit":
        raise ModelError(f"AUR source {commit} is not a commit")
    return commit


def bound_paths(root: Path, manifest: InstallManifest, transforms: dict[str, dict[str, Any]]) -> tuple[str, ...]:
    """Repository files whose bytes the generated recipe depends on."""

    paths = set(BOUND_AUTHORITIES)
    for payload in manifest.files:
        paths.add(payload.source.resolve().relative_to(root.resolve()).as_posix())
    for upstream, transform in transforms.items():
        paths.add(
            f"integrations/{upstream}/native-route/{transform['patch']['path']}"
        )
    return tuple(sorted(paths))


def _bind_source_tree(
    root: Path, repository: Path, commit: str, paths: tuple[str, ...]
) -> None:
    request = "".join(f"{commit}:{path}\n" for path in paths).encode("utf-8")
    result = _git(repository, ["cat-file", "--batch"], input_bytes=request)
    if result.returncode != 0:
        raise ModelError("cannot read the referenced HyperFlux source tree")
    stream = result.stdout
    offset = 0
    for path in paths:
        end = stream.index(b"\n", offset)
        header = stream[offset:end].decode("utf-8", "replace").split()
        offset = end + 1
        if len(header) != 3 or header[1] != "blob":
            raise ModelError(f"AUR source revision does not contain {path}")
        size = int(header[2])
        content = stream[offset : offset + size]
        offset += size + 1
        local = root / path
        if not local.is_file() or local.read_bytes() != content:
            raise ModelError(
                f"AUR source revision differs from the generating tree at {path}"
            )


def _upstream_pins(
    root: Path,
    transforms: dict[str, dict[str, Any]],
    checkouts: Mapping[str, Path],
    urls: Mapping[str, str],
) -> tuple[UpstreamPin, ...]:
    unknown = set(checkouts) - set(UPSTREAM_ORDER)
    if unknown:
        raise ModelError(f"unknown upstream checkout: {', '.join(sorted(unknown))}")
    pins = []
    for upstream in UPSTREAM_ORDER:
        transform = transforms[upstream]
        commit = transform["upstream"]["commit"]
        checksum = SKIP
        checkout = checkouts.get(upstream)
        if checkout is not None:
            if _git(checkout, ["cat-file", "-t", commit]).stdout.strip() != b"commit":
                raise ModelError(f"{upstream} checkout does not contain the pinned commit {commit}")
            checksum = git_archive_sha256(checkout, commit)
        pins.append(
            UpstreamPin(
                id=upstream,
                url=urls.get(upstream, transform["upstream"]["repository"]),
                commit=commit,
                checksum=checksum,
                transform=transform,
            )
        )
    return tuple(pins)


def _source_entry(name: str, url: str, fragment: str) -> str:
    return f"{name}::git+{url}#{fragment}"


def _source_entries(source: SourceReference, upstreams: tuple[UpstreamPin, ...], name: str) -> list[str]:
    if source.kind == "tag":
        first = _source_entry(name, source.url, f"tag={source.name}?signed")
    else:
        first = _source_entry(name, source.url, f"commit={source.commit}")
    return [first, *(_source_entry(item.id, item.url, f"commit={item.commit}") for item in upstreams)]


def _checksum_lines(records: list[tuple[str, str]]) -> list[str]:
    return [f"{digest}  {path}" for digest, path in records]


def _transform_function(
    pin: UpstreamPin, source_name: str, deployment: Any
) -> list[str]:
    transform = pin.transform
    patch = f"$srcdir/{source_name}/integrations/{pin.id}/native-route/{transform['patch']['path']}"
    excludes = " ".join(f"--exclude={_shell_word(item)}" for item in UPSTREAM_EXCLUDES[pin.id])
    result = json.dumps(
        {
            "schema": TRANSFORM_RESULT_SCHEMA[pin.id],
            "source_commit": pin.commit,
            "patch_sha256": transform["patch"]["sha256"],
            "transformed_files": [
                {"path": record["path"], "sha256": record["transformed_sha256"]}
                for record in transform["files"]
            ],
            "network_access_executed": False,
            "hardware_queried": False,
            "hardware_write_executed": False,
        },
        indent=2,
        sort_keys=True,
    )
    patch_arguments = "--batch --forward --fuzz=0 --no-backup-if-mismatch -p1"
    lines = [
        f"_hfx_transform_{pin.id}() {{",
        "  set -o pipefail",
        f'  local upstream="$srcdir/{pin.id}" native="$srcdir/{pin.id}-native"',
        f'  local patch="{patch}"',
        f'  [[ "$(git -C "$upstream" rev-parse HEAD)" == {_shell_word(pin.commit)} ]] || return 1',
        f"  printf '%s  %s\\n' {_shell_word(transform['patch']['sha256'])} \"$patch\" |",
        "    sha256sum --check --strict --quiet - || return 1",
        '  rm -rf -- "$native"',
        '  mkdir -- "$native" || return 1',
        f'  tar -C "$upstream" {excludes} -cf - . | tar -C "$native" -xf - || return 1',
        '  (cd "$native" && sha256sum --check --strict --quiet -) <<\'EOF\' || return 1',
        *_checksum_lines(
            [(record["source_sha256"], record["path"]) for record in transform["files"]]
        ),
        "EOF",
        f'  patch --directory="$native" --dry-run {patch_arguments} -i "$patch" || return 1',
        f'  patch --directory="$native" {patch_arguments} -i "$patch" || return 1',
        '  (cd "$native" && sha256sum --check --strict --quiet -) <<\'EOF\' || return 1',
        *_checksum_lines(
            [(record["transformed_sha256"], record["path"]) for record in transform["files"]]
        ),
        "EOF",
    ]
    if pin.id == "openrazer":
        driver = deployment.driver
        modules = " ".join(sorted(driver.modules)) + " "
        lines.extend(
            [
                '  local conf="$native/install_files/dkms/dkms.conf" modules',
                f"  grep -qxF {_shell_word(f'PACKAGE_NAME=\"{driver.dkms_name}\"')} \"$conf\" || return 1",
                f"  grep -qxF {_shell_word(f'PACKAGE_VERSION=\"{driver.dkms_version}\"')} \"$conf\" || return 1",
                "  modules=\"$(sed -n 's/^BUILT_MODULE_NAME\\[[0-9]\\{1,\\}\\]=\"\\([a-z0-9_-]\\{1,\\}\\)\"$/\\1/p' \"$conf\" |",
                "    LC_ALL=C sort | tr '\\n' ' ')\" || return 1",
                f"  [[ \"$modules\" == {_shell_word(modules)} ]] || return 1",
            ]
        )
    lines.extend(
        [
            f'  cat > "$native/{TRANSFORM_RESULT}" <<\'EOF\' || return 1',
            *result.splitlines(),
            "EOF",
            f'  chmod 0600 "$native/{TRANSFORM_RESULT}" || return 1',
        ]
    )
    lines.append("}")
    return lines


def _environment_function(source_name: str) -> list[str]:
    return [
        "_hfx_environment() {",
        "  export RUSTUP_TOOLCHAIN=stable",
        f'  export CARGO_TARGET_DIR="$srcdir/{CARGO_TARGET_DIRECTORY}"',
        "  export CARGO_INCREMENTAL=0 CARGO_NET_OFFLINE=true CARGO_PROFILE_RELEASE_STRIP=symbols",
        "  export CC=clang CXX=clang++ CMAKE_GENERATOR=Ninja",
        '  export HFX_SOURCE_REVISION="$_commit"',
        '  export RUSTFLAGS="${RUSTFLAGS:-} --remap-path-prefix=$srcdir=."',
        '  export CFLAGS="${CFLAGS:-} -ffile-prefix-map=$srcdir=."',
        '  export CXXFLAGS="${CXXFLAGS:-} -ffile-prefix-map=$srcdir=."',
        f'  cd "$srcdir/{source_name}"',
        "}",
    ]


def _cargo_groups(builds: list[BuildSpec]) -> list[tuple[str, str, list[str]]]:
    groups: dict[tuple[str, str], list[str]] = {}
    for build in builds:
        if build.package is None or build.cargo_profile is None or build.target is None:
            raise ModelError(f"build {build.id}: incomplete Cargo declaration")
        groups.setdefault((build.package, build.cargo_profile), []).append(build.target)
    return [(package, profile, targets) for (package, profile), targets in sorted(groups.items())]


def _build_source(build: BuildSpec, source_name: str) -> str:
    if build.kind == "cargo-binary":
        return f'"$srcdir/{CARGO_TARGET_DIRECTORY}/{build.cargo_profile}/{build.target}"'
    if build.kind == "cmake-module":
        return f'"$srcdir/{OPENRGB_BUILD_DIRECTORY}/{build.output}"'
    if build.kind == "source-transform-file":
        return f'"$srcdir/openrazer-native/{build.source}"'
    raise ModelError(f"build {build.id}: no AUR install rule for {build.kind}")


def _openrazer_projection(destination: str) -> list[str]:
    """The DKMS tree projection the repository pipeline builds, file for file."""

    target = f'"$pkgdir{destination}'
    native = '"$srcdir/openrazer-native'
    return [
        f'  install -Dm0644 {native}/Makefile" {target}/Makefile"',
        f'  install -Dm0644 {native}/install_files/dkms/dkms.conf" {target}/dkms.conf"',
        f'  install -Dm0644 {native}/driver/Makefile" {target}/driver/Makefile"',
        "  local file count=3 licensed=0",
        f'  for file in {native}/driver/"*.c {native}/driver/"*.h; do',
        '    [[ -f "$file" && ! -L "$file" ]] || continue',
        f'    install -Dm0644 "$file" {target}/driver/${{file##*/}}"',
        "    count=$((count + 1))",
        "  done",
        f'  if [[ -f {native}/LICENSE" && ! -L {native}/LICENSE" ]]; then',
        f'    install -Dm0644 {native}/LICENSE" {target}/LICENSE"',
        "    count=$((count + 1)) licensed=1",
        "  fi",
        f'  for file in {native}/LICENSES/"*.txt; do',
        '    [[ -f "$file" && ! -L "$file" ]] || continue',
        f'    install -Dm0644 "$file" {target}/LICENSES/${{file##*/}}"',
        "    count=$((count + 1)) licensed=1",
        "  done",
        "  (( count >= 8 && licensed == 1 )) || return 1",
    ]


def _package_function(
    output: SplitOutput, manifest: InstallManifest, source_name: str
) -> list[str]:
    builds = {build.id: build for build in manifest.builds}
    lines = [f"package_{output.package_name}() {{"]
    lines.extend(
        line for line in package_function_metadata(output) if not line.endswith("=()")
    )
    for destination, mode in output.directory_modes:
        lines.append(f'  install -dm{mode:04o} "$pkgdir{destination}"')
    for build_id in output.builds:
        build = builds[build_id]
        if build.destination is None or build.mode is None:
            raise ModelError(f"build {build.id}: no destination")
        if build.kind == "source-transform":
            lines.extend(_openrazer_projection(build.destination))
            continue
        lines.append(
            f'  install -Dm{build.mode:04o} {_build_source(build, source_name)} "$pkgdir{build.destination}"'
        )
    for payload in manifest.files:
        if payload.component not in output.payloads:
            continue
        relative = payload.source.resolve().relative_to(manifest.root.resolve()).as_posix()
        lines.append(
            f'  install -Dm{payload.mode:04o} "$srcdir/{source_name}/{relative}" "$pkgdir{payload.destination}"'
        )
    lines.append("}")
    return lines


def render_pkgbuild(
    *,
    authority: AurAuthority,
    split: ArchSplit,
    manifest: InstallManifest,
    architecture: str,
    mode: str,
    source: SourceReference,
    upstreams: tuple[UpstreamPin, ...],
    validpgpkeys: tuple[str, ...],
    disclosures: tuple[str, ...],
    deployment: Any,
) -> str:
    name = authority.source_name
    sources = _source_entries(source, upstreams, name)
    sums = [source.checksum, *(item.checksum for item in upstreams)]
    cargo = [
        build
        for output in split.outputs
        for build_id in output.builds
        for build in manifest.builds
        if build.id == build_id and build.kind == "cargo-binary"
    ]
    cmake = [
        build
        for output in split.outputs
        for build_id in output.builds
        for build in manifest.builds
        if build.id == build_id and build.kind == "cmake-module"
    ]
    lines = [
        GENERATED_HEADER,
        "# SPDX-License-Identifier: 0BSD",
        f"# Recipe mode: {mode}",
    ]
    lines.extend(f"# Qualification only: {item}" for item in disclosures)
    lines.extend(pkgbuild_guidance(split, architecture))
    lines.extend(
        [
            "",
            f"pkgbase={split.pkgbase}",
            f"pkgname={_shell_array([output.package_name for output in split.outputs])}",
            f"pkgver={split.version}",
            f"pkgrel={split.package_release}",
            f"pkgdesc={_shell_word(split.description)}",
            f"arch={_shell_array([architecture])}",
            f"url={_shell_word(split.homepage)}",
            f"license={_shell_array(list(split.licenses))}",
            f"makedepends={_shell_array(list(authority.makedepends))}",
            f"options={_shell_array(list(authority.options))}",
            f"source={_shell_array(sources)}",
            f"sha256sums={_shell_array(sums)}",
        ]
    )
    if validpgpkeys:
        lines.append(f"validpgpkeys={_shell_array(list(validpgpkeys))}")
    lines.extend([f"_commit={_shell_word(source.commit)}", ""])
    for pin in upstreams:
        lines.extend(_transform_function(pin, name, deployment))
        lines.append("")
    lines.extend(_environment_function(name))
    lines.extend(
        [
            "",
            "prepare() {",
            *(f"  _hfx_transform_{pin.id}" for pin in upstreams),
            f'  cd "$srcdir/{name}"',
            "  export RUSTUP_TOOLCHAIN=stable",
            "  cargo fetch --locked --target \"$(rustc -vV | sed -n 's/^host: //p')\"",
            "}",
            "",
            "build() {",
            "  _hfx_environment",
        ]
    )
    for package, profile, targets in _cargo_groups(cargo):
        binaries = " ".join(f"--bin {target}" for target in targets)
        lines.append(f"  cargo build --frozen --profile {profile} --package {package} {binaries}")
    for build in cmake:
        lines.extend(
            [
                f'  cmake -S {build.source} -B "$srcdir/{OPENRGB_BUILD_DIRECTORY}" \\',
                "    -DCMAKE_BUILD_TYPE=Release -DBUILD_TESTING=OFF \\",
                '    -DHFX_SOURCE_REVISION="$_commit" \\',
                '    -DHFX_OPENRGB_SOURCE_DIR="$srcdir/openrgb" \\',
                '    -DHFX_OPENRGB_NATIVE_SOURCE_DIR="$srcdir/openrgb-native"',
                f'  cmake --build "$srcdir/{OPENRGB_BUILD_DIRECTORY}" --target {build.target}',
            ]
        )
    packages = sorted({build.package for build in cargo if build.package})
    lines.extend(
        [
            "}",
            "",
            "check() {",
            "  _hfx_environment",
            "  cargo test --frozen " + " ".join(f"--package {item}" for item in packages),
            "}",
            "",
        ]
    )
    for output in split.outputs:
        lines.extend(_package_function(output, manifest, name))
        lines.append("")
    return "\n".join(lines)


def _srcinfo_attribute(name: str, values: tuple[str, ...] | list[str]) -> list[str]:
    return [f"\t{name} = {value}" for value in values]


def render_srcinfo(
    *,
    authority: AurAuthority,
    split: ArchSplit,
    architecture: str,
    source: SourceReference,
    upstreams: tuple[UpstreamPin, ...],
    validpgpkeys: tuple[str, ...],
) -> str:
    """`.SRCINFO` exactly as `makepkg --printsrcinfo` prints it, minus comments."""

    sources = _source_entries(source, upstreams, authority.source_name)
    lines = [f"pkgbase = {split.pkgbase}"]
    lines += _srcinfo_attribute("pkgdesc", [split.description])
    lines += _srcinfo_attribute("pkgver", [split.version])
    lines += _srcinfo_attribute("pkgrel", [str(split.package_release)])
    lines += _srcinfo_attribute("url", [split.homepage])
    lines += _srcinfo_attribute("arch", [architecture])
    lines += _srcinfo_attribute("license", split.licenses)
    lines += _srcinfo_attribute("makedepends", authority.makedepends)
    lines += _srcinfo_attribute("options", authority.options)
    lines += _srcinfo_attribute("source", sources)
    lines += _srcinfo_attribute("validpgpkeys", validpgpkeys)
    lines += _srcinfo_attribute(
        "sha256sums", [source.checksum, *(item.checksum for item in upstreams)]
    )
    for output in split.outputs:
        optional = [f"{item.package}: {item.purpose}" for item in output.optional_dependencies]
        lines += ["", f"pkgname = {output.package_name}"]
        lines += _srcinfo_attribute("pkgdesc", [output.description])
        lines += _srcinfo_attribute("license", output.licenses)
        lines += _srcinfo_attribute("depends", output.dependencies)
        lines += _srcinfo_attribute("optdepends", optional)
        lines += _srcinfo_attribute("provides", output.provides)
        lines += _srcinfo_attribute("conflicts", output.conflicts)
        lines += _srcinfo_attribute("replaces", output.replaces)
        lines += _srcinfo_attribute("backup", output.backup)
    return "\n".join(lines) + "\n"


def render_reuse(authority: AurAuthority) -> str:
    return "\n".join(
        [
            "version = 1",
            "",
            "[[annotations]]",
            'path = ["PKGBUILD", ".SRCINFO", "REUSE.toml"]',
            f'SPDX-FileCopyrightText = "{authority.copyright}"',
            'SPDX-License-Identifier = "0BSD"',
            "",
        ]
    )


def render_license(authority: AurAuthority) -> str:
    return f"Copyright {authority.copyright}\n\n{ZERO_BSD_TERMS}"


def generate_aur_recipe(
    root: Path,
    *,
    tag: str | None = None,
    commit: str | None = None,
    source_repository: Path | None = None,
    source_url: str | None = None,
    upstream_checkouts: Mapping[str, Path] | None = None,
    upstream_urls: Mapping[str, str] | None = None,
    transforms: Mapping[str, dict[str, Any]] | None = None,
    split: ArchSplit | None = None,
    signing_fingerprint: str | None = None,
    environment: Mapping[str, str] | None = None,
    architecture: str = "x86_64",
    provider_alignment: ProviderAlignment | None = None,
) -> AurRecipe:
    """Render the AUR recipe for one exact HyperFlux revision.

    A signed tag produces a publication recipe; a commit produces a local
    qualification recipe whose limits are written into the PKGBUILD.
    """

    root = root.resolve()
    if (tag is None) == (commit is None):
        raise ModelError("AUR recipe needs exactly one of a signed tag or a qualification commit")
    mode = PUBLICATION if tag is not None else QUALIFICATION
    authority = load_aur_authority(root)
    split = split or load_arch_split(root)
    if architecture not in split.architectures:
        raise ModelError(f"AUR recipe architecture {architecture} is not admitted")
    if mode == PUBLICATION and not split.active:
        raise ModelError(
            f"Arch split starts at {split.first_release}; {split.full_version} "
            "has no four-output AUR recipe"
        )
    alignment = provider_alignment or evaluate_provider_alignment(root, split=split)
    if alignment.candidate != split.full_version:
        raise ModelError("OpenRazer provider alignment was evaluated for another release")
    if mode == PUBLICATION and not alignment.passed:
        raise ModelError(
            "OpenRazer provider alignment gate failed: " + "; ".join(alignment.problems)
        )
    manifest = load_install_manifest(root)
    deployment = load_native_deployment(root)
    loaded = {
        "openrazer": load_openrazer_transform(root),
        "openrgb": load_openrgb_transform(root),
    }
    loaded.update(dict(transforms or {}))
    for upstream, transform in loaded.items():
        patch = root / "integrations" / upstream / "native-route" / transform["patch"]["path"]
        if sha256_file(patch) != transform["patch"]["sha256"]:
            raise ModelError(f"{upstream} native patch differs from its transform lock")
    fingerprint = signing_fingerprint or load_arch_repository_policy(root).primary_fingerprint
    if not FINGERPRINT.fullmatch(fingerprint):
        raise ModelError("AUR signing key must be a full primary fingerprint")
    repository = (source_repository or root).resolve()
    if tag is not None:
        resolved = _signed_tag(repository, tag, fingerprint, environment)
        reference_kind, reference_name, archive_reference = "tag", tag, tag
    else:
        resolved = _commit(repository, commit or "")
        reference_kind, reference_name, archive_reference = "commit", resolved, resolved
    paths = bound_paths(root, manifest, loaded)
    _bind_source_tree(root, repository, resolved, paths)
    source = SourceReference(
        kind=reference_kind,
        name=reference_name,
        commit=resolved,
        url=source_url or authority.repository,
        checksum=git_archive_sha256(repository, archive_reference),
    )
    upstreams = _upstream_pins(root, loaded, upstream_checkouts or {}, upstream_urls or {})
    disclosures: list[str] = []
    if mode == QUALIFICATION:
        disclosures.append(
            f"source {resolved} is a commit, not a signed tag, so makepkg cannot verify its signer"
        )
        if not split.active:
            disclosures.append(
                f"{split.full_version} precedes the four-output release {split.first_release}"
            )
    disclosures.extend(f"provider gate: {problem}" for problem in alignment.problems)
    for pin in upstreams:
        if pin.checksum != SKIP:
            continue
        if mode == PUBLICATION:
            raise ModelError(
                f"publication recipe needs a local {pin.id} checkout at {pin.commit} "
                "to compute its source checksum"
            )
        disclosures.append(f"{pin.id} {pin.commit} checksum is SKIP; no local checkout was given")
    validpgpkeys = (fingerprint,) if mode == PUBLICATION else ()
    pkgbuild = render_pkgbuild(
        authority=authority,
        split=split,
        manifest=manifest,
        architecture=architecture,
        mode=mode,
        source=source,
        upstreams=upstreams,
        validpgpkeys=validpgpkeys,
        disclosures=tuple(disclosures),
        deployment=deployment,
    )
    srcinfo = render_srcinfo(
        authority=authority,
        split=split,
        architecture=architecture,
        source=source,
        upstreams=upstreams,
        validpgpkeys=validpgpkeys,
    )
    return AurRecipe(
        mode=mode,
        version=split.full_version,
        source=source,
        upstreams=upstreams,
        validpgpkeys=validpgpkeys,
        bound_paths=paths,
        disclosures=tuple(disclosures),
        files={
            "PKGBUILD": pkgbuild,
            ".SRCINFO": srcinfo,
            "LICENSE": render_license(authority),
            "REUSE.toml": render_reuse(authority),
        },
    )


def write_aur_recipe(recipe: AurRecipe, output: Path) -> tuple[Path, ...]:
    """Write the recipe as the flat file set an AUR Git repository holds."""

    output = output.expanduser()
    if output.is_symlink() or (output.exists() and (not output.is_dir() or any(output.iterdir()))):
        raise ModelError("AUR recipe output must be a new or empty directory")
    output.mkdir(parents=True, exist_ok=True)
    written = []
    for name in RECIPE_FILES:
        path = output / name
        path.write_text(recipe.files[name], encoding="utf-8")
        path.chmod(0o644)
        written.append(path)
    return tuple(written)
