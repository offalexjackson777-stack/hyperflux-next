"""Source-built AUR recipe for the four-output Arch topology.

The recipe is rendered from the same authorities as the signed repository:
`packaging/arch-split.json` decides the outputs and their relations,
`packaging/install.json` decides every installed path and mode, and the two
native-route transforms pin the exact upstream OpenRazer and OpenRGB commits
and patches. Nothing prebuilt enters the recipe: makepkg fetches one signed
HyperFlux tag and the two pinned upstream commits, verifies their checksums,
fetches the locked Cargo graph in `prepare()`, and builds, checks, and
packages with the network disabled.

A recipe can only describe sources it can bind. Every authority and payload
file it reads must be byte-identical at the referenced revision, and a
publication recipe additionally needs a signed annotated tag made by the
project key and a computed checksum for every upstream commit.
"""

