@dataclass(frozen=True)
class RpmPlan:
    """Everything one `.rpm` declares, derived from one split output."""

    output: str
    package_name: str
    version: str
    release: str
    architecture: str
    summary: str
    description: tuple[str, ...]
    licenses: tuple[str, ...]
    depends: tuple[str, ...]
    scriptlet_requires: tuple[tuple[str, str], ...]
    suggests: tuple[str, ...]
    conflicts: tuple[str, ...]
    provides: tuple[str, ...]
    replaces: tuple[str, ...]
    config_files: tuple[str, ...]
    scripts: tuple[tuple[str, str], ...]
    changelog_entry: str

    @property
    def evr(self) -> str:
        return f"{self.version}-{self.release}"

    @property
    def license(self) -> str:
        return " AND ".join(self.licenses)

    @property
    def file_name(self) -> str:
        return f"{self.package_name}-{self.evr}.{self.architecture}.rpm"


def rpm_relation(value: str, label: str) -> str:
    """Translate one Arch relation (`name`, `name=1.0`, `name>=1.0`)."""

    if RPM_RELATION.fullmatch(value):
        return value
    match = ARCH_RELATION.fullmatch(value)
    if match is None:
        raise ModelError(f"{label}: {value!r} cannot be expressed as an RPM relation")
    if match.group("operator") is None:
        return match.group("name")
    relation = (
        f"{match.group('name')} {RPM_OPERATORS[match.group('operator')]} "
        f"{match.group('version')}"
    )
    if not RPM_RELATION.fullmatch(relation):
        raise ModelError(f"{label}: {value!r} cannot be expressed as an RPM relation")
    return relation


def rpmlint_config() -> str:
    """The rpmlint configuration that accepts exactly the errors in RPMLINT_FILTERS."""

    lines = [GENERATED_HEADER, "Filters = ["]
    for reason, patterns in RPMLINT_FILTERS:
        lines.append(f"    # {reason}")
        for pattern in patterns:
            if "'" in pattern or "\n" in pattern or not pattern.startswith("hyperflux-next-"):
                raise ModelError(f"rpmlint filter cannot be written: {pattern}")
            try:
                re.compile(pattern)
            except re.error as error:
                raise ModelError(f"rpmlint filter is not a pattern: {pattern}: {error}") from error
            lines.append(f"    '{pattern}',")
    lines.append("]")
    return "\n".join(lines) + "\n"


def rpmlint_override_config() -> str:
    """The rpmlint override that lets the named filters apply on openSUSE.

    openSUSE blocks filters for the checks its security team reviews for its
    own packages, and a plain configuration can only add to that list. These
    packages are not part of openSUSE, every filter names one of them, and the
    distribution's own filters do not name those checks.

    Why the whole list is cleared rather than only the four checks the filters
    need today (permissions-directory-setuid-bit, permissions-missing-postin,
    permissions-missing-requires and systemd-tmpfile-entry-unauthorized):
    rpmlint 2.x merges configuration files in a fixed order (its defaults, the
    system directories such as /etc/xdg/rpmlint, then --config) and has only
    two list operations. A plain file appends the items it names, and a file
    whose name contains ".override." replaces the list. Nothing removes one
    item. `Filters` can therefore be extended without touching openSUSE's
    own filters, which hyperflux-next.toml does, but `BlockedFilters` can only
    grow or be replaced. Keeping openSUSE's other blocked checks would mean
    copying its list of about sixty names into this file, and the copy would
    silently go stale whenever openSUSE changes it. Clearing it lets only
    configured `Filters` patterns hide those checks: openSUSE's own filters
    do not name them, and every pattern here names a HyperFlux package and the
    exact path it accepts.
    """

    return "\n".join(
        [
            GENERATED_HEADER,
            "# openSUSE blocks filters for checks its security team reviews for its own",
            "# packages. These packages are not part of openSUSE, so the filters in",
            f"# {RPMLINT_FILTERS_FILE} apply to them; each one names its package.",
            "BlockedFilters = []",
        ]
    ) + "\n"


def rpmlint_configs() -> tuple[tuple[str, str], ...]:
    """The files of the rpmlint configuration directory, by name."""

    return (
        (RPMLINT_FILTERS_FILE, rpmlint_config()),
        (RPMLINT_OVERRIDE_FILE, rpmlint_override_config()),
    )


def target_outputs(split: ArchSplit, target: DistributionTarget) -> tuple[SplitOutput, ...]:
    """The split outputs of the editions an RPM target carries."""

    if target.package_format != "rpm":
        raise ModelError(f"distribution {target.id} is not an RPM-format target")
    return edition_outputs(split, target)


def _scripts(output: SplitOutput, runtime: LinuxRuntime) -> tuple[tuple[str, str], ...]:
    post: list[str] = []
    preun: list[str] = []
    postun: list[str] = []
    if "dkms" in output.dependency_roles:
        kernel = runtime.kernel
        source = PurePosixPath(kernel.source_directory)
        if f"{source}/dkms.conf" not in output.file_destinations:
            raise ModelError(
                f"{output.package_name}: the DKMS output does not own {source}/dkms.conf"
            )
        name, version = kernel.dkms_name, kernel.dkms_version
        # Register and build only. On Fedora and openSUSE `dkms install`
        # loads the module into the running kernel; DKMS installs the built
        # module itself at the next boot.
        post.extend(
            [
                # openSUSE keeps the DKMS upgrade lock in a directory that
                # systemd-tmpfiles only creates at boot.
                "if [ -f /usr/lib/tmpfiles.d/dkms.conf ] && [ -x /usr/bin/systemd-tmpfiles ]; then",
                "  systemd-tmpfiles --create dkms.conf || :",
                "fi",
                f"dkms add -m {name} -v {version} --rpm_safe_upgrade || :",
                "for build in /lib/modules/*/build; do",
                '  [ -f "$build/Makefile" ] || continue',
                '  kernel=${build%/build}',
                '  kernel=${kernel##*/}',
                f'  dkms build -m {name} -v {version} -k "$kernel" || :',
                "done",
            ]
        )
        # An upgrade to the same version keeps the module registered.
        preun.extend(
            [
                f'if [ -n "$(dkms status -m {name} -v {version} 2>/dev/null)" ]; then',
                f"  dkms remove -m {name} -v {version} --all --rpm_safe_upgrade || :",
                "fi",
            ]
        )
    sysusers = sorted(
        PurePosixPath(path).name
        for path in output.file_destinations
        if path.startswith(SYSUSERS_DIRECTORY) and path.endswith(".conf")
    )
    tmpfiles = sorted(
        PurePosixPath(path).name
        for path in output.file_destinations
        if path.startswith(TMPFILES_DIRECTORY) and path.endswith(".conf")
    )
    systemd = any(path.startswith(SYSTEMD_DIRECTORY) for path in output.file_destinations)
    udev = any(path.startswith(UDEV_RULES_DIRECTORY) for path in output.file_destinations)
    for name in sysusers:
        # The package requires systemd before this scriptlet runs.
        post.append(f"systemd-sysusers {name}")
    for name in tmpfiles:
        post.extend(
            [
                "if [ -x /usr/bin/systemd-tmpfiles ]; then",
                f"  systemd-tmpfiles --create {name} || :",
                "fi",
            ]
        )
    reload: list[str] = []
    if systemd:
        reload.append("  systemctl daemon-reload || :")
    if udev:
        reload.append("  udevadm control --reload || :")
    if reload:
        # Only a running systemd can be reloaded. Units stay disabled and
        # stopped: first run enables them explicitly, then reboots. Removal
        # never stops them either, as on Arch: the removal steps in the
        # generated distribution page turn them off first.
        guarded = ["if [ -d /run/systemd/system ]; then", *reload, "fi"]
        post.extend(guarded)
        postun.extend(guarded)
    scripts: list[tuple[str, str]] = []
    for phase, body in (("post", post), ("preun", preun), ("postun", postun)):
        if body:
            scripts.append((phase, "\n".join([GENERATED_HEADER, *body, "exit 0"])))
    return tuple(scripts)


def _scriptlet_requires(
    output: SplitOutput, target: DistributionTarget, scripts: tuple[tuple[str, str], ...]
) -> tuple[tuple[str, str], ...]:
    """Packages a scriptlet runs, so RPM installs them first and removes them last."""

    phases = {phase for phase, _ in scripts}
    required: list[tuple[str, str]] = []
    if "dkms" in output.dependency_roles:
        package = target.dependency_roles["dkms"]
        required.extend([("post", package), ("preun", package)])
    if any(path.startswith(SYSUSERS_DIRECTORY) for path in output.file_destinations):
        if "service-manager" not in output.dependency_roles:
            raise ModelError(
                f"{output.package_name}: system users need the service-manager role"
            )
        required.append(("post", target.dependency_roles["service-manager"]))
    if any(phase not in phases for phase, _ in required):
        raise ModelError(f"{output.package_name}: a scriptlet requirement has no scriptlet")
    return tuple(required)


def rpm_plans(
    split: ArchSplit,
    target: DistributionTarget,
    runtime: LinuxRuntime,
    catalog: DistributionCatalog,
) -> tuple[RpmPlan, ...]:
    """Derive the `.rpm` metadata of every output the target carries."""

    release = target.release
    if release is None:
        raise ModelError(f"distribution {target.id}: an RPM target names its release")
    if len(target.architectures) != 1:
        raise ModelError(f"distribution {target.id}: exactly one architecture is supported")
    architecture = next(iter(target.architectures.values()))
    full_version = rpm_version(split.version, split.package_release)
    version, package_release = full_version.rsplit("-", 1)
    outputs = target_outputs(split, target)
    plans: list[RpmPlan] = []
    for output in outputs:
        label = f"{target.id} {output.package_name}"
        component = target.component(output.edition)
        if any(role not in component.dependency_roles for role in output.dependency_roles):
            raise ModelError(f"{label}: dependency role is outside the edition contract")
        role_packages = tuple(target.dependency_roles[role] for role in output.dependency_roles)
        # The split records Arch role packages; an RPM target maps roles only.
        arch_roles = catalog.targets["arch"].dependency_roles
        if set(output.external_dependencies) != {
            arch_roles[role] for role in output.dependency_roles
        }:
            raise ModelError(
                f"{label}: RPM outputs depend only on roles and siblings, "
                "not on Arch package names"
            )
        siblings = tuple(
            rpm_exact(split.output(sibling).package_name, full_version)
            for sibling in output.sibling_dependencies
        )
        request = split.edition_output(output.edition).id == output.id
        optional = component.optional_dependencies if request else ()
        if not output.builds and not any(
            path.startswith("/usr/src/") for path in output.file_destinations
        ):
            raise ModelError(f"{label}: an output without builds must be DKMS sources")
        entry_request = split.edition_output(output.edition).package_name
        role_line = (
            "This package installs the whole edition."
            if request
            else f"It is installed as a dependency of {entry_request}."
        )
        for item in output.backup:
            if not SPEC_PATH.fullmatch("/" + item):
                raise ModelError(f"{label}: configuration path {item!r} is not representable")
        scripts = _scripts(output, runtime)
        plans.append(
            RpmPlan(
                output=output.id,
                package_name=output.package_name,
                version=version,
                release=package_release,
                # Outputs without builds carry only sources and data.
                architecture="noarch" if not output.builds else architecture,
                summary=output.description,
                description=(
                    f"Part of the {runtime.product.display_name} Core edition for "
                    f"{release.distribution} {release.version}.",
                    role_line,
                ),
                licenses=output.licenses,
                depends=tuple(dict.fromkeys([*role_packages, *siblings])),
                scriptlet_requires=_scriptlet_requires(output, target, scripts),
                suggests=tuple(
                    rpm_relation(item.package, f"{label} suggestion") for item in optional
                ),
                conflicts=tuple(
                    rpm_relation(item, f"{label} conflict") for item in output.conflicts
                ),
                provides=tuple(
                    rpm_relation(item, f"{label} provide") for item in output.provides
                ),
                replaces=tuple(
                    rpm_relation(item, f"{label} replace") for item in output.replaces
                ),
                config_files=tuple(sorted("/" + item for item in output.backup)),
                scripts=scripts,
                changelog_entry=(
                    f"Build {runtime.product.display_name} {runtime.product.version} "
                    f"for {release.distribution} {release.version}."
                ),
            )
        )
    check_edition_contract(plans, outputs, target)
    return tuple(plans)


def _spec_text(value: str, label: str) -> str:
    """One spec line: no line breaks, and `%` escaped so no macro expands."""

    if "\n" in value or "\r" in value or not value.strip():
        raise ModelError(f"{label} cannot be written into a spec")
    return value.replace("%", "%%")


def changelog_date(epoch: int) -> str:
    moment = time.gmtime(epoch)
    return f"{WEEKDAYS[moment.tm_wday]} {MONTHS[moment.tm_mon - 1]} {moment.tm_mday:02d} {moment.tm_year}"


def file_entries(plan: RpmPlan, root: Path) -> tuple[tuple[str, str, int], ...]:
    """(kind, path, mode) for every staged file and every directory the package owns.

    A package owns the directories named after HyperFlux; system
    directories such as `/usr/lib/systemd/system` stay with their owners.
    """

    entries: list[tuple[str, str, int]] = []
    for path in sorted(root.rglob("*")):
        relative = "/" + path.relative_to(root).as_posix()
        if path.is_symlink() or not (path.is_dir() or path.is_file()):
            raise ModelError(f"{plan.package_name}: {relative} is not a file or directory")
        if not SPEC_PATH.fullmatch(relative):
            raise ModelError(f"{plan.package_name}: {relative!r} cannot be named in a spec")
        mode = stat.S_IMODE(path.stat().st_mode)
        if path.is_dir():
            if "hyperflux" in relative:
                entries.append(("dir", relative, mode))
            continue
        if mode & (stat.S_ISUID | stat.S_ISGID | stat.S_ISVTX):
            raise ModelError(f"{plan.package_name}: staged file carries a special mode bit")
        entries.append(("file", relative, mode))
    return tuple(entries)


def _file_flag(plan: RpmPlan, path: str) -> str:
    if path in plan.config_files:
        return "%config(noreplace) "
    if path.startswith(LICENSE_DIRECTORY):
        return "%license "
    if path.startswith(DOC_DIRECTORY):
        return "%doc "
    return ""


def spec_text(
    split: ArchSplit,
    plans: tuple[RpmPlan, ...],
    entries: dict[str, tuple[tuple[str, str, int], ...]],
    epoch: int,
) -> str:
    """The one spec that builds every output as a subpackage of the pkgbase."""

    if not plans or len({(plan.version, plan.release) for plan in plans}) != 1:
        raise ModelError("RPM subpackages must share one version")
    first = plans[0]
    lines = [GENERATED_HEADER, "# SPDX-License-Identifier: GPL-2.0-only"]
    lines.extend(f"%global {name} {value}" for name, value in SPEC_GLOBALS)
    lines.extend(
        [
            "",
            f"Name: {split.pkgbase}",
            f"Version: {first.version}",
            f"Release: {first.release}",
            f"Summary: {_spec_text(split.description, 'summary')}",
            f"License: {' AND '.join(split.licenses)}",
            f"URL: {_spec_text(split.homepage, 'homepage')}",
            f"Packager: {RPM_PACKAGER}",
            "AutoReqProv: no",
            "",
            "%description",
            _spec_text(split.description, "description") + ".",
        ]
    )
    for plan in plans:
        lines.extend(
            [
                "",
                f"%package -n {plan.package_name}",
                f"Summary: {_spec_text(plan.summary, f'{plan.package_name} summary')}",
                f"License: {plan.license}",
                "AutoReqProv: no",
            ]
        )
        if plan.architecture == "noarch":
            lines.append("BuildArch: noarch")
        lines.extend(f"Requires: {item}" for item in plan.depends)
        lines.extend(f"Requires({phase}): {item}" for phase, item in plan.scriptlet_requires)
        for tag, values in (
            ("Suggests", plan.suggests),
            ("Conflicts", plan.conflicts),
            ("Provides", plan.provides),
            ("Obsoletes", plan.replaces),
        ):
            lines.extend(f"{tag}: {item}" for item in values)
        lines.extend(
            [
                "",
                f"%description -n {plan.package_name}",
                *(_spec_text(line, f"{plan.package_name} description") for line in plan.description),
            ]
        )
    lines.extend(
        [
            "",
            "%prep",
            "",
            "%build",
            "",
            "%install",
            "cp -a %{hfx_payload}/. %{buildroot}/",
        ]
    )
    for plan in plans:
        for phase, body in plan.scripts:
            if phase not in SCRIPTLETS:
                raise ModelError(f"{plan.package_name}: unsupported scriptlet {phase}")
            lines.extend(["", f"%{phase} -n {plan.package_name}", body.replace("%", "%%")])
    for plan in plans:
        lines.extend(["", f"%files -n {plan.package_name}", "%defattr(-,root,root,-)"])
        for kind, path, mode in entries[plan.output]:
            if kind == "dir":
                lines.append(f"%dir %attr({mode:04o},root,root) {path}")
            else:
                lines.append(f"%attr({mode:04o},root,root) {_file_flag(plan, path)}{path}")
    lines.extend(
        [
            "",
            "%changelog",
            f"* {changelog_date(epoch)} {RPM_PACKAGER} - {first.evr}",
            f"- {_spec_text(first.changelog_entry, 'changelog entry')}",
            "",
        ]
    )
    return "\n".join(lines)


def _environment(workspace: Path, epoch: int) -> dict[str, str]:
    home = workspace / "home"
    home.mkdir(exist_ok=True)
    temporary = workspace / "tmp"
    temporary.mkdir(exist_ok=True)
    environment = {
        "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
        # No ~/.rpmmacros of the person building can change the packages.
        "HOME": str(home),
        "TMPDIR": str(temporary),
        "LC_ALL": "C.UTF-8",
        "TZ": "UTC",
        "SOURCE_DATE_EPOCH": str(epoch),
    }
    return environment


def _run(command: list[str], environment: dict[str, str], label: str, timeout: int = 300) -> str:
    try:
        result = subprocess.run(
            command,
            env=environment,
            check=False,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise ModelError(f"{label} failed: {error}") from error
    if result.returncode != 0:
        detail = " ".join(part for part in (result.stdout.strip(), result.stderr.strip()) if part)
        raise ModelError(f"{label} failed with exit status {result.returncode}: {detail}")
    return result.stdout


def _run_rpmbuild(
    spec: Path, payload: Path, packages: Path, workspace: Path, architecture: str, epoch: int
) -> None:
    environment = _environment(workspace, epoch)
    _run(
        [
            "rpmbuild",
            "-bb",
            "--quiet",
            "--target",
            architecture,
            "--define",
            f"_topdir {workspace / 'topdir'}",
            "--define",
            f"_tmppath {environment['TMPDIR']}",
            "--define",
            f"_rpmdir {packages}",
            "--define",
            "_build_name_fmt %%{NAME}-%%{VERSION}-%%{RELEASE}.%%{ARCH}.rpm",
            "--define",
            f"hfx_payload {payload}",
            str(spec),
        ],
        environment,
        "RPM package build",
        timeout=600,
    )


def _query(package: Path, query: str, environment: dict[str, str]) -> str:
    return _run(
        ["rpm", "-qp", "--nosignature", "--queryformat", query, str(package)],
        environment,
        "RPM package query",
        timeout=120,
    )


def parse_cpio(content: bytes) -> list[tuple[str, int, int, int, int, bytes]]:
    """Parse a `newc` archive into (name, mode, uid, gid, mtime, content)."""

    entries: list[tuple[str, int, int, int, int, bytes]] = []
    offset = 0
    while True:
        header = content[offset : offset + 110]
        if len(header) != 110 or header[:6] not in {b"070701", b"070702"}:
            raise ModelError("RPM payload is not a newc cpio archive")
        try:
            fields = [int(header[6 + 8 * index : 14 + 8 * index], 16) for index in range(13)]
        except ValueError as error:
            raise ModelError("RPM payload cpio header is malformed") from error
        _, mode, uid, gid, links, mtime, size, _, _, _, _, name_size, _ = fields
        name_start = offset + 110
        name_end = name_start + name_size
        if name_size < 1 or content[name_end - 1 : name_end] != b"\0":
            raise ModelError("RPM payload cpio name is malformed")
        name = content[name_start : name_end - 1].decode("utf-8")
        data_start = (name_end + 3) & ~3
        data_end = data_start + size
        if data_end > len(content):
            raise ModelError("RPM payload cpio member is truncated")
        if name == "TRAILER!!!":
            return entries
        if links != 1 and not stat.S_ISDIR(mode):
            raise ModelError("RPM payload contains a hard link")
        entries.append((name, mode, uid, gid, mtime, content[data_start:data_end]))
        offset = (data_end + 3) & ~3


def _payload(package: Path, environment: dict[str, str]) -> bytes:
    try:
        result = subprocess.run(
            ["rpm2cpio", str(package)],
            env=environment,
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise ModelError(f"cannot read RPM payload: {error}") from error
    if result.returncode != 0:
        raise ModelError(f"cannot read RPM payload: exit status {result.returncode}")
    return result.stdout


def _relations(text: str) -> list[tuple[str, str]]:
    """Parse `name<TAB>flags<TAB>version<TAB>type` lines into (relation, type)."""

    relations = []
    for line in text.splitlines():
        name, flags, version, kind = line.split("\t")
        relation = f"{name} {flags.strip()} {version}" if flags.strip() else name
        relations.append((relation, kind))
    return relations


def verify_rpm_package(
    package: Path,
    *,
    plan: RpmPlan,
    output: SplitOutput,
    stage: SplitStage,
    entries: tuple[tuple[str, str, int], ...],
    epoch: int,
    forbidden: tuple[bytes, ...],
    workspace: Path,
) -> None:
    """Check one built `.rpm` against its plan and its split stage."""

    environment = _environment(workspace, epoch)
    _run(
        ["rpmkeys", "--checksig", "--nosignature", str(package)],
        environment,
        "RPM digest check",
        timeout=120,
    )
    if any(value in package.read_bytes() for value in forbidden):
        raise ModelError(f"{plan.package_name}: package header contains a private build path")
    header = _query(
        package,
        "%{NAME}\\n%{VERSION}\\n%{RELEASE}\\n%{ARCH}\\n%{LICENSE}\\n%{BUILDTIME}\\n"
        "%{BUILDHOST}\\n%{PACKAGER}\\n%{PAYLOADCOMPRESSOR}\\n%{SUMMARY}\\n",
        environment,
    ).split("\n")
    expected_header = [
        plan.package_name,
        plan.version,
        plan.release,
        plan.architecture,
        plan.license,
        str(epoch),
        RPM_BUILD_HOST,
        RPM_PACKAGER,
        "xz",
        plan.summary,
        "",
    ]
    if header != expected_header:
        raise ModelError(f"{plan.package_name}: RPM header differs from its plan")

    relation_query = (
        "[%{{{tag}NAME}}\\t%{{{tag}FLAGS:depflags}}\\t%{{{tag}VERSION}}\\t%{{{tag}FLAGS:deptype}}\\n]"
    )
    requires = _relations(_query(package, relation_query.format(tag="REQUIRE"), environment))
    declared: dict[str, set[str]] = {}
    for relation, kind in requires:
        if IMPLICIT_REQUIREMENT.fullmatch(relation.split(" ")[0]):
            continue
        declared.setdefault(relation, set()).add(kind)
    expected: dict[str, set[str]] = {item: {"manual"} for item in plan.depends}
    for phase, item in plan.scriptlet_requires:
        expected.setdefault(item, set()).add(phase)
    if {key: value for key, value in declared.items()} != expected:
        raise ModelError(f"{plan.package_name}: RPM requirements differ from the plan")
    # rpmbuild provides the package name, and for an architecture-specific
    # package also the name qualified by its instruction set.
    self_provides = {
        f"{plan.package_name} = {plan.evr}",
        f"{plan.package_name}({plan.architecture.replace('_', '-')}) = {plan.evr}",
    }
    for tag, values in (
        ("CONFLICT", plan.conflicts),
        ("OBSOLETE", plan.replaces),
        ("SUGGEST", plan.suggests),
        ("PROVIDE", plan.provides),
    ):
        found = {relation for relation, _ in _relations(_query(package, relation_query.format(tag=tag), environment))}
        if tag == "PROVIDE":
            found -= self_provides
        if found != set(values):
            raise ModelError(f"{plan.package_name}: RPM {tag.lower()}s differ from the plan")
    for phase in SCRIPTLETS:
        body = _query(package, f"%{{{SCRIPTLET_TAGS[phase]}}}", environment)
        expected_body = dict(plan.scripts).get(phase, "(none)")
        if body != expected_body:
            raise ModelError(f"{plan.package_name}: {phase} scriptlet differs from the plan")

    files = _query(
        package,
        "[%{FILENAMES}\\t%{FILEMODES:octal}\\t%{FILEUSERNAME}\\t%{FILEGROUPNAME}\\t"
        "%{FILEMTIMES}\\t%{FILEFLAGS:fflags}\\n]",
        environment,
    )
    listed: dict[str, tuple[int, str]] = {}
    for line in files.splitlines():
        name, mode, user, group, mtime, flags = line.split("\t")
        if (user, group) != ("root", "root") or int(mtime) != epoch:
            raise ModelError(f"{plan.package_name}: file ownership or time is not canonical")
        listed[name] = (int(mode, 8), flags)
    expected_files = {
        path: (
            (stat.S_IFDIR if kind == "dir" else stat.S_IFREG) | mode,
            _file_flag(plan, path) if kind == "file" else "",
        )
        for kind, path, mode in entries
    }
    flag_letters = {"%config(noreplace) ": "cn", "%license ": "l", "%doc ": "d", "": ""}
    if set(listed) != set(expected_files) or any(
        listed[path] != (mode, flag_letters[flag]) for path, (mode, flag) in expected_files.items()
    ):
        raise ModelError(f"{plan.package_name}: RPM file list differs from the plan")

    stage_entries: list[tuple[str, int, bytes]] = []
    directory_modes: dict[str, int] = {}
    names: set[str] = set()
    for name, mode, uid, gid, mtime, content in parse_cpio(_payload(package, environment)):
        relative = name.removeprefix("./")
        path = PurePosixPath(relative)
        if relative in names or path.is_absolute() or ".." in path.parts or not relative:
            raise ModelError("RPM payload contains an unsafe or duplicate member")
        names.add(relative)
        if (uid, gid) != (0, 0) or mtime != epoch:
            raise ModelError(f"{plan.package_name}: payload ownership or time is not canonical")
        if stat.S_ISDIR(mode):
            directory_modes["/" + relative] = stat.S_IMODE(mode)
            continue
        if not stat.S_ISREG(mode):
            raise ModelError("RPM payload contains an unsupported member type")
        if mode & (stat.S_ISUID | stat.S_ISGID | stat.S_ISVTX):
            raise ModelError(f"{plan.package_name}: {relative} carries a setuid, setgid or sticky bit")
        if any(value in content for value in forbidden):
            raise ModelError(f"{plan.package_name}: payload contains a private build path")
        stage_entries.append((relative, stat.S_IMODE(mode), content))
    for destination, expected_mode in output.directory_modes:
        if directory_modes.get(destination.rstrip("/")) != expected_mode:
            raise ModelError(f"{plan.package_name}: directory mode differs for {destination}")
    digest = hashlib.sha256()
    for name, mode, content in sorted(stage_entries):
        digest.update(name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(f"{mode:04o}".encode("ascii"))
        digest.update(b"\0")
        digest.update(hashlib.sha256(content).digest())
    if len(stage_entries) != stage.file_count or digest.hexdigest() != stage.payload_sha256:
        raise ModelError(f"{plan.package_name}: payload differs from its split stage")


def build_rpm_packages(
    *,
    repository_root: Path,
    workspace_root: Path,
    packages: Path,
    split: ArchSplit,
    target: DistributionTarget,
    runtime: LinuxRuntime,
    catalog: DistributionCatalog,
    epoch: int,
    stages: dict[str, SplitStage],
) -> tuple[tuple[RpmPlan, SplitStage, Path], ...]:
    """Build every output from one spec and verify each `.rpm` against its stage."""

    plans = rpm_plans(split, target, runtime, catalog)
    if [plan.output for plan in plans] != list(stages):
        raise ModelError(f"distribution {target.id}: split stages differ from the package plans")
    architecture = next(iter(target.architectures.values()))
    forbidden = tuple(
        item.encode("utf-8")
        for item in {str(repository_root), str(Path.home()), "/tmp/hyperflux-", str(workspace_root)}
        if len(item) > 1
    )
    payload = workspace_root / "payload"
    payload.mkdir()
    entries: dict[str, tuple[tuple[str, str, int], ...]] = {}
    modes: list[tuple[str, int]] = []
    for plan in plans:
        output = split.output(plan.output)
        root = workspace_root / f"rpm-{plan.output}"
        shutil.copytree(stages[plan.output].root, root, symlinks=True)
        elf = check_c_runtime(root, target)
        if plan.architecture == "noarch" and elf:
            raise ModelError(f"{plan.package_name}: an architecture-independent package has ELF files")
        normalize_tree(root, epoch, output.directory_modes)
        verify_directory_modes(root, output.directory_modes, f"{plan.package_name} payload")
        entries[plan.output] = file_entries(plan, root)
        # The outputs never share a file, so one build root holds them all.
        shutil.copytree(root, payload, symlinks=True, dirs_exist_ok=True)
        modes.extend(output.directory_modes)
    normalize_tree(payload, epoch, tuple(modes))
    spec = workspace_root / f"{split.pkgbase}.spec"
    spec.write_text(spec_text(split, plans, entries, epoch), encoding="utf-8")
    spec.chmod(0o644)
    _run_rpmbuild(spec, payload, packages, workspace_root, architecture, epoch)
    expected = {plan.file_name for plan in plans}
    produced = {path.name for path in packages.iterdir()}
    if produced != expected:
        raise ModelError(
            f"distribution {target.id}: rpmbuild produced {sorted(produced)}, "
            f"expected {sorted(expected)}"
        )
    built = []
    for plan in plans:
        package = packages / plan.file_name
        if package.is_symlink() or not package.is_file():
            raise ModelError(f"{plan.package_name}: rpmbuild did not produce a regular file")
        package.chmod(0o644)
        os.utime(package, (epoch, epoch))
        verify_rpm_package(
            package,
            plan=plan,
            output=split.output(plan.output),
            stage=stages[plan.output],
            entries=entries[plan.output],
            epoch=epoch,
            forbidden=forbidden,
            workspace=workspace_root,
        )
        built.append((plan, stages[plan.output], package))
    return tuple(built)


def build_rpm_distribution(
    *,
    root: Path,
    build_manifest: Path,
    output: Path,
    runtime: LinuxRuntime,
    catalog: DistributionCatalog,
    target: DistributionTarget,
) -> DistributionPackageResult:
    """Stage the target's editions, split them, and build one `.rpm` per output."""

    if target.package_format != "rpm" or target.release is None:
        raise ModelError(f"distribution {target.id} is not an RPM-format target")
    artifacts = load_artifact_set(root, build_manifest)
    architecture = target.architecture_for(artifacts.target)
    split = load_arch_split(root)
    if not split.active:
        raise ModelError(f"distribution {target.id} needs the active Arch split")
    outputs = target_outputs(split, target)
    packages = output / "packages"
    packages.mkdir()
    with tempfile.TemporaryDirectory(prefix=f"hyperflux-{target.id}-package-") as temporary:
        workspace_root = Path(temporary)
        stages = {
            component_id: stage_rootfs(
                root,
                build_manifest,
                workspace_root / f"{component_id}-root",
                component_id,
            )
            for component_id in target.components
        }
        split_root = workspace_root / "split"
        split_root.mkdir()
        split_stages = split_edition_stages(
            split, stages, split_root, artifacts.source_date_epoch, outputs
        )
        build_root = workspace_root / "build"
        build_root.mkdir()
        built = build_rpm_packages(
            repository_root=root,
            workspace_root=build_root,
            packages=packages,
            split=split,
            target=target,
            runtime=runtime,
            catalog=catalog,
            epoch=artifacts.source_date_epoch,
            stages=split_stages,
        )
    if {plan.architecture for plan, _, _ in built} - {"noarch", architecture}:
        raise ModelError(f"distribution {target.id}: package architecture is unexpected")
    results = tuple(
        DistributionPackageArtifact(
            component=plan.output,
            package_name=plan.package_name,
            package=package,
            payload_sha256=stage.payload_sha256,
            payload_file_count=stage.file_count,
        )
        for plan, stage, package in built
    )
    manifest_value = {
        "$schema": MANIFEST_SCHEMA_URL,
        "schema": MANIFEST_SCHEMA,
        "source": {
            "revision": artifacts.revision,
            "source_date_epoch": artifacts.source_date_epoch,
            "distribution_catalog_sha256": catalog.source_sha256,
            "arch_split_sha256": split.source_sha256,
            "artifact_manifest_sha256": sha256_file(build_manifest),
        },
        "distribution": target.id,
        "release": {
            "distribution": target.release.distribution,
            "version": target.release.version,
        },
        "maturity": target.maturity,
        "architecture": architecture,
        "packages": [
            {
                "output": plan.output,
                "distribution_component": split.output(plan.output).edition,
                "name": plan.package_name,
                "version": plan.version,
                "release": plan.release,
                "architecture": plan.architecture,
                "requires": list(plan.depends),
                "file": package.name,
                "sha256": sha256_file(package),
                "size": package.stat().st_size,
                "payload_sha256": stage.payload_sha256,
                "payload_files": stage.file_count,
            }
            for plan, stage, package in sorted(built, key=lambda item: item[0].package_name)
        ],
    }
    manifest = output / BUILD_MANIFEST_NAME
    manifest.write_text(
        json.dumps(manifest_value, indent=2, ensure_ascii=True) + "\n",
        encoding="utf-8",
    )
    manifest.chmod(0o644)
    os.utime(manifest, (artifacts.source_date_epoch, artifacts.source_date_epoch))
    lint = output / RPMLINT_CONFIG_NAME
    lint.mkdir(mode=0o755)
    for name, text in rpmlint_configs():
        path = lint / name
        path.write_text(text, encoding="utf-8")
        path.chmod(0o644)
        os.utime(path, (artifacts.source_date_epoch, artifacts.source_date_epoch))
    lint.chmod(0o755)
    os.utime(lint, (artifacts.source_date_epoch, artifacts.source_date_epoch))
    return DistributionPackageResult(
        packages=results,
        manifest=manifest,
        distribution=target.id,
        architecture=architecture,
    )
