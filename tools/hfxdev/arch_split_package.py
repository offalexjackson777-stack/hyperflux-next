GENERATED_HEADER = "# Generated by ./hfx package distro. Do not edit manually."
# Fields that describe how and when a package was built rather than what it
# is. Every other PKGINFO field is part of the product contract and must be
# identical across the signed repository and the AUR.
BUILD_ONLY_PKGINFO_FIELDS = frozenset(
    {"builddate", "packager", "size", "makedepend", "checkdepend", "xdata"}
)
CONTRACT_PKGINFO_FIELDS = (
    "pkgname",
    "pkgbase",
    "pkgver",
    "pkgdesc",
    "url",
    "arch",
    "license",
    "replaces",
    "group",
    "conflict",
    "provides",
    "backup",
    "depend",
    "optdepend",
)


@dataclass(frozen=True)
class SplitStage:
    output: str
    root: Path
    payload_sha256: str
    file_count: int


def output_contract(
    split: ArchSplit, output: SplitOutput, architecture: str
) -> dict[str, tuple[str, ...]]:
    """PKGINFO fields every channel must produce for one output."""

    if architecture not in split.architectures:
        raise ModelError(f"Arch split: architecture {architecture} is not admitted")
    return {
        "pkgname": (output.package_name,),
        "pkgbase": (split.pkgbase,),
        "pkgver": (split.full_version,),
        "pkgdesc": (output.description,),
        "url": (split.homepage,),
        "arch": (architecture,),
        "license": output.licenses,
        "replaces": output.replaces,
        "group": (),
        "conflict": output.conflicts,
        "provides": output.provides,
        "backup": output.backup,
        "depend": output.dependencies,
        "optdepend": tuple(
            f"{item.package}: {item.purpose}" for item in output.optional_dependencies
        ),
    }


def product_fields(metadata: dict[str, tuple[str, ...]]) -> dict[str, tuple[str, ...]]:
    """Reduce parsed PKGINFO to the product contract, rejecting unknown fields."""

    unknown = set(metadata) - set(CONTRACT_PKGINFO_FIELDS) - BUILD_ONLY_PKGINFO_FIELDS
    if unknown:
        raise ModelError(
            f"Arch package PKGINFO carries unreviewed fields: {', '.join(sorted(unknown))}"
        )
    return {field: tuple(metadata.get(field, ())) for field in CONTRACT_PKGINFO_FIELDS}


def package_function_metadata(output: SplitOutput) -> list[str]:
    """Per-package PKGBUILD variables shared by every recipe channel."""

    optional = [f"{item.package}: {item.purpose}" for item in output.optional_dependencies]
    return [
        f"  pkgdesc={_shell_word(output.description)}",
        f"  license={_shell_array(list(output.licenses))}",
        f"  depends={_shell_array(list(output.dependencies))}",
        f"  optdepends={_shell_array(optional)}",
        f"  conflicts={_shell_array(list(output.conflicts))}",
        f"  provides={_shell_array(list(output.provides))}",
        f"  replaces={_shell_array(list(output.replaces))}",
        f"  backup={_shell_array(list(output.backup))}",
    ]


def render_repository_pkgbuild(
    split: ArchSplit, architecture: str, payload_sha256: dict[str, str]
) -> str:
    payloads = [f"payload-{output.id}.tar" for output in split.outputs]
    lines = [
        GENERATED_HEADER,
        "# SPDX-License-Identifier: GPL-2.0-only",
        f"pkgbase={split.pkgbase}",
        f"pkgname={_shell_array([output.package_name for output in split.outputs])}",
        f"pkgver={split.version}",
        f"pkgrel={split.package_release}",
        f"pkgdesc={_shell_word(split.description)}",
        f"arch={_shell_array([architecture])}",
        f"url={_shell_word(split.homepage)}",
        f"license={_shell_array(list(split.licenses))}",
        "options=('!strip' '!debug')",
        f"source={_shell_array(payloads)}",
        f"noextract={_shell_array(payloads)}",
        f"sha256sums={_shell_array([payload_sha256[output.id] for output in split.outputs])}",
        "",
    ]
    for output in split.outputs:
        lines.append(f"package_{output.package_name}() {{")
        lines.extend(package_function_metadata(output))
        lines.append(f'  bsdtar -xf "$srcdir/payload-{output.id}.tar" -C "$pkgdir"')
        lines.extend(["}", ""])
    return "\n".join(lines)


def _copy_parents(source_root: Path, destination_root: Path, relative: PurePosixPath) -> None:
    current_source = source_root
    current_destination = destination_root
    for part in relative.parts:
        current_source = current_source / part
        current_destination = current_destination / part
        if current_destination.is_dir():
            continue
        current_destination.mkdir()
        current_destination.chmod(stat.S_IMODE(current_source.stat().st_mode))


def split_edition_stages(
    split: ArchSplit,
    stages: dict[str, StageResult],
    workspace: Path,
    epoch: int,
) -> dict[str, SplitStage]:
    """Move every staged edition file into the output that owns it."""

    roots: dict[str, Path] = {}
    for output in split.outputs:
        root = workspace / f"{output.id}-root"
        root.mkdir()
        roots[output.id] = root
    for edition, stage in stages.items():
        for path in tree_files(stage.root):
            relative = PurePosixPath(path.relative_to(stage.root).as_posix())
            owner = split.output(split.owner_of("/" + relative.as_posix()))
            if owner.edition != edition:
                raise ModelError(
                    f"Arch split: {relative} was staged by {edition} but belongs to "
                    f"{owner.package_name}"
                )
            _copy_parents(stage.root, roots[owner.id], relative.parent)
            destination = roots[owner.id].joinpath(*relative.parts)
            shutil.copyfile(path, destination)
            destination.chmod(stat.S_IMODE(path.stat().st_mode))
    expected_files = sum(stage.file_count for stage in stages.values())
    results: dict[str, SplitStage] = {}
    for output in split.outputs:
        root = roots[output.id]
        normalize_tree(root, epoch, output.directory_modes)
        verify_directory_modes(root, output.directory_modes, f"{output.package_name} payload")
        files = tree_files(root)
        if not files:
            raise ModelError(f"Arch split: {output.package_name} owns no staged files")
        results[output.id] = SplitStage(
            output=output.id,
            root=root,
            payload_sha256=tree_digest(root, files),
            file_count=len(files),
        )
    if sum(item.file_count for item in results.values()) != expected_files:
        raise ModelError("Arch split: output payloads do not add up to the edition stages")
    return results


def verify_split_package(
    package: Path,
    *,
    split: ArchSplit,
    output: SplitOutput,
    architecture: str,
    epoch: int,
    stage: SplitStage,
    forbidden: tuple[bytes, ...],
) -> None:
    metadata_files: dict[str, bytes] = {}
    entries: list[tuple[tarfile.TarInfo, bytes | None]] = []
    directory_modes: dict[str, int] = {}
    digest = hashlib.sha256()
    payload_files = 0
    try:
        with tarfile.open(package, "r:*") as archive:
            members = archive.getmembers()
            names = [member.name for member in members]
            if len(names) != len(set(names)):
                raise ModelError("Arch package contains duplicate members")
            if names != sorted(names, key=lambda name: PurePosixPath(name).as_posix()):
                raise ModelError("Arch package members are not in canonical order")
            for member in members:
                path = PurePosixPath(member.name)
                if path.is_absolute() or ".." in path.parts:
                    raise ModelError("Arch package contains an unsafe member path")
                if member.uid != 0 or member.gid != 0 or member.mtime != epoch:
                    raise ModelError("Arch package member metadata is not canonical")
                if member.isdir():
                    entries.append((copy.copy(member), None))
                    directory_modes["/" + path.as_posix().rstrip("/")] = member.mode
                    continue
                if not member.isfile():
                    raise ModelError("Arch package contains an unsupported member type")
                stream = archive.extractfile(member)
                if stream is None:
                    raise ModelError("Arch package regular file has no content")
                content = stream.read()
                entries.append((copy.copy(member), content))
                if any(value in content for value in forbidden):
                    raise ModelError("Arch package contains a private or temporary build path")
                if member.name.startswith("."):
                    metadata_files[member.name] = content
                    continue
                payload_files += 1
                digest.update(member.name.encode("utf-8"))
                digest.update(b"\0")
                digest.update(f"{member.mode:04o}".encode("ascii"))
                digest.update(b"\0")
                digest.update(hashlib.sha256(content).digest())
    except (OSError, tarfile.TarError) as error:
        raise ModelError(f"cannot verify Arch package: {error}") from error
    if set(metadata_files) != {".BUILDINFO", ".MTREE", ".PKGINFO"}:
        raise ModelError(
            "Arch split package metadata members are incomplete or unexpected; "
            "outputs carry no install script"
        )
    if metadata_files[".MTREE"] != _canonical_arch_mtree(entries, epoch):
        raise ModelError("Arch package MTREE does not describe the canonical archive")
    for destination, expected in output.directory_modes:
        actual = directory_modes.get(destination.rstrip("/"))
        if actual != expected:
            found = "missing" if actual is None else f"{actual:04o}"
            raise ModelError(
                f"Arch package directory mode differs for {destination}: "
                f"expected {expected:04o}, found {found}"
            )
    if payload_files != stage.file_count or digest.hexdigest() != stage.payload_sha256:
        raise ModelError(f"{output.package_name} payload differs from its split stage")
    info = _arch_metadata(metadata_files[".PKGINFO"], "PKGINFO")
    if product_fields(info) != output_contract(split, output, architecture):
        raise ModelError(f"{output.package_name} PKGINFO differs from the split contract")
    for key, expected in {
        "packager": CANONICAL_ARCH_PACKAGER,
        "builddate": str(epoch),
    }.items():
        if _one_arch_value(info, key, "PKGINFO") != expected:
            raise ModelError(f"Arch package PKGINFO {key} does not match its authority")
    build_info = _arch_metadata(metadata_files[".BUILDINFO"], "BUILDINFO")
    for key, expected in {
        "pkgname": output.package_name,
        "pkgbase": split.pkgbase,
        "pkgver": split.full_version,
        "pkgarch": architecture,
        "packager": CANONICAL_ARCH_PACKAGER,
        "builddate": str(epoch),
        "builddir": CANONICAL_ARCH_BUILD_ROOT,
        "startdir": CANONICAL_ARCH_BUILD_ROOT,
    }.items():
        if _one_arch_value(build_info, key, "BUILDINFO") != expected:
            raise ModelError(f"Arch package BUILDINFO {key} does not match its authority")


def build_split_packages(
    *,
    repository_root: Path,
    workspace_root: Path,
    packages: Path,
    split: ArchSplit,
    architecture: str,
    epoch: int,
    stages: dict[str, StageResult],
) -> tuple[DistributionPackageArtifact, ...]:
    if not split.active:
        raise ModelError(
            f"Arch split starts at {split.first_release}; {split.full_version} "
            "keeps the two-package release"
        )
    split_root = workspace_root / "split"
    split_root.mkdir()
    split_stages = split_edition_stages(split, stages, split_root, epoch)
    workspace = workspace_root / "makepkg"
    workspace.mkdir()
    digests: dict[str, str] = {}
    for output in split.outputs:
        payload = workspace / f"payload-{output.id}.tar"
        write_payload_tar(split_stages[output.id].root, payload, epoch)
        digests[output.id] = sha256_file(payload)
    pkgbuild = workspace / "PKGBUILD"
    pkgbuild.write_text(
        render_repository_pkgbuild(split, architecture, digests), encoding="utf-8"
    )
    for path in [pkgbuild, *(workspace / f"payload-{item}.tar" for item in digests)]:
        path.chmod(0o644)
        os.utime(path, (epoch, epoch))
    _run_makepkg(workspace, packages, epoch)
    built = sorted(packages.glob("*.pkg.tar.*"))
    if len(built) != len(split.outputs) or any(
        not item.is_file() or item.is_symlink() for item in built
    ):
        raise ModelError("Arch split build did not produce every output")
    by_name: dict[str, Path] = {}
    for package in built:
        _canonicalize_arch_package(package, epoch)
        name = _arch_package_name(package)
        if name in by_name:
            raise ModelError("Arch split build produced duplicate package names")
        by_name[name] = package
    forbidden = tuple(
        item.encode("utf-8")
        for item in {str(repository_root), str(Path.home()), "/tmp/hyperflux-"}
        if len(item) > 1
    )
    results = []
    for output in split.outputs:
        package = by_name.get(output.package_name)
        if package is None:
            raise ModelError(f"Arch split build omitted {output.package_name}")
        stage = split_stages[output.id]
        verify_split_package(
            package,
            split=split,
            output=output,
            architecture=architecture,
            epoch=epoch,
            stage=stage,
            forbidden=forbidden,
        )
        results.append(
            DistributionPackageArtifact(
                component=output.id,
                package_name=output.package_name,
                package=package,
                payload_sha256=stage.payload_sha256,
                payload_file_count=stage.file_count,
            )
        )
    return tuple(results)
