"""Signed-repository build of the four-output Arch topology.

The edition stages stay the source of truth for file content. Each staged
file moves to the one output that owns it in `packaging/arch-split.json`, so
the union of the four packages is byte-for-byte the union of the two edition
stages. No output carries an install script: pacman's systemd and DKMS hooks
run sysusers, tmpfiles, daemon and udev reloads, and module builds whenever a
transaction touches their paths.
"""

