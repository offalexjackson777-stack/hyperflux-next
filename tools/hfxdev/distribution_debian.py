@dataclass(frozen=True)
class DebianPlan:
    """Everything one `.deb` declares, derived from one split output."""

    output: str
    package_name: str
    version: str
    architecture: str
    section: str
    homepage: str
    synopsis: str
    extended_description: tuple[str, ...]
    licenses: tuple[str, ...]
    depends: tuple[str, ...]
    suggests: tuple[str, ...]
    conflicts: tuple[str, ...]
    provides: tuple[str, ...]
    replaces: tuple[str, ...]
    conffiles: tuple[str, ...]
    scripts: tuple[tuple[str, str], ...]
    changelog_entry: str
    codename: str

    @property
    def file_name(self) -> str:
        return f"{self.package_name}_{self.version}_{self.architecture}.deb"

    @property
    def doc_directory(self) -> PurePosixPath:
        return PurePosixPath("usr/share/doc") / self.package_name


def debian_relation(value: str, label: str) -> str:
    """Translate one Arch relation (`name`, `name=1.0`, `name>=1.0`)."""

    if DEBIAN_RELATION.fullmatch(value):
        return value
    match = ARCH_RELATION.fullmatch(value)
    if match is None:
        raise ModelError(f"{label}: {value!r} cannot be expressed as a Debian relation")
    if match.group("operator") is None:
        return match.group("name")
    relation = (
        f"{match.group('name')} "
        f"({DEBIAN_OPERATORS[match.group('operator')]} {match.group('version')})"
    )
    if not DEBIAN_RELATION.fullmatch(relation):
        raise ModelError(f"{label}: {value!r} cannot be expressed as a Debian relation")
    return relation


def target_outputs(split: ArchSplit, target: DistributionTarget) -> tuple[SplitOutput, ...]:
    """The split outputs of the editions a Debian target carries."""

    if target.package_format != "deb":
        raise ModelError(f"distribution {target.id} is not a Debian-format target")
    return edition_outputs(split, target)


def edition_outputs(split: ArchSplit, target: DistributionTarget) -> tuple[SplitOutput, ...]:
    """The split outputs of the editions a target carries, in split order."""

    outputs = tuple(output for output in split.outputs if output.edition in target.components)
    if {output.edition for output in outputs} != set(target.components):
        raise ModelError(f"distribution {target.id}: an edition has no split outputs")
    return outputs


def _scripts(output: SplitOutput, runtime: LinuxRuntime) -> tuple[tuple[str, str], ...]:
    configure: list[str] = []
    remove: list[str] = []
    after_remove: list[str] = []
    if "dkms" in output.dependency_roles:
        kernel = runtime.kernel
        source = PurePosixPath(kernel.source_directory)
        if f"{source}/dkms.conf" not in output.file_destinations:
            raise ModelError(
                f"{output.package_name}: the DKMS output does not own {source}/dkms.conf"
            )
        name, version = kernel.dkms_name, kernel.dkms_version
        configure.append(f'{DKMS_COMMON_POSTINST} {name} {version} "" "" "${{2:-}}"')
        remove.extend(
            [
                f'if [ -n "$(dkms status -m {name} -v {version} 2>/dev/null)" ]; then',
                f"  dkms remove -m {name} -v {version} --all",
                "fi",
            ]
        )
    sysusers = sorted(
        PurePosixPath(path).name
        for path in output.file_destinations
        if path.startswith(SYSUSERS_DIRECTORY) and path.endswith(".conf")
    )
    tmpfiles = sorted(
        PurePosixPath(path).name
        for path in output.file_destinations
        if path.startswith(TMPFILES_DIRECTORY) and path.endswith(".conf")
    )
    systemd = any(path.startswith(SYSTEMD_DIRECTORY) for path in output.file_destinations)
    udev = any(path.startswith(UDEV_RULES_DIRECTORY) for path in output.file_destinations)
    for name in sysusers:
        # The package depends on systemd, so a missing tool is an error.
        configure.append(f"systemd-sysusers {name}")
    for name in tmpfiles:
        configure.extend(
            [
                "if [ -x /usr/bin/systemd-tmpfiles ]; then",
                f"  systemd-tmpfiles --create {name} || true",
                "fi",
            ]
        )
    reload: list[str] = []
    if systemd:
        reload.append("  systemctl daemon-reload")
    if udev:
        reload.append("  udevadm control --reload || true")
    if reload:
        # Only a running systemd can be reloaded. Units stay disabled and
        # stopped: first run enables them explicitly, then reboots.
        guarded = ["if [ -d /run/systemd/system ]; then", *reload, "fi"]
        configure.extend(guarded)
        after_remove.extend(guarded)

    def script(cases: tuple[tuple[str, list[str]], ...]) -> str:
        lines = ["#!/bin/sh", GENERATED_HEADER, "set -e", "", 'case "$1" in']
        for pattern, body in cases:
            lines.append(f"  {pattern})")
            lines.extend(f"    {line}" for line in body)
            lines.append("    ;;")
        lines.extend(["esac", "", "exit 0", ""])
        return "\n".join(lines)

    scripts: list[tuple[str, str]] = []
    if configure:
        scripts.append(("postinst", script((("configure", configure),))))
    if remove:
        scripts.append(("prerm", script((("remove|upgrade|deconfigure", remove),))))
    if after_remove:
        scripts.append(("postrm", script((("remove|purge", after_remove),))))
    return tuple(scripts)


def debian_plans(
    split: ArchSplit,
    target: DistributionTarget,
    runtime: LinuxRuntime,
    catalog: DistributionCatalog,
) -> tuple[DebianPlan, ...]:
    """Derive the `.deb` metadata of every output the target carries."""

    release = target.release
    if release is None:
        raise ModelError(f"distribution {target.id}: a Debian target names its release")
    architecture = next(iter(target.architectures.values()))
    if len(target.architectures) != 1:
        raise ModelError(f"distribution {target.id}: exactly one architecture is supported")
    version = debian_version(split.version, split.package_release)
    outputs = target_outputs(split, target)
    plans: list[DebianPlan] = []
    for output in outputs:
        label = f"{target.id} {output.package_name}"
        component = target.component(output.edition)
        if any(role not in component.dependency_roles for role in output.dependency_roles):
            raise ModelError(f"{label}: dependency role is outside the edition contract")
        role_packages = tuple(target.dependency_roles[role] for role in output.dependency_roles)
        # The split records Arch role packages plus any Arch-only package
        # names. A Debian target maps roles only; Arch names have no meaning.
        arch_roles = catalog.targets["arch"].dependency_roles
        if set(output.external_dependencies) != {
            arch_roles[role] for role in output.dependency_roles
        }:
            raise ModelError(
                f"{label}: Debian outputs depend only on roles and siblings, "
                "not on Arch package names"
            )
        siblings = tuple(
            debian_exact(split.output(sibling).package_name, version)
            for sibling in output.sibling_dependencies
        )
        request = split.edition_output(output.edition).id == output.id
        optional = component.optional_dependencies if request else ()
        if not output.builds and not any(
            path.startswith("/usr/src/") for path in output.file_destinations
        ):
            raise ModelError(f"{label}: an output without builds must be DKMS sources")
        entry_request = split.edition_output(output.edition).package_name
        role_line = (
            "This package installs the whole edition."
            if request
            else f"It is installed as a dependency of {entry_request}."
        )
        plans.append(
            DebianPlan(
                output=output.id,
                package_name=output.package_name,
                version=version,
                # Outputs without builds carry only sources and data.
                architecture="all" if not output.builds else architecture,
                section="kernel" if "dkms" in output.dependency_roles else "admin",
                homepage=catalog.homepage,
                synopsis=output.description,
                extended_description=(
                    f"Part of the {runtime.product.display_name} Core edition for "
                    f"{release.distribution} {release.version}.",
                    role_line,
                ),
                licenses=output.licenses,
                depends=tuple(dict.fromkeys([*role_packages, *siblings])),
                suggests=tuple(
                    debian_relation(item.package, f"{label} suggestion") for item in optional
                ),
                conflicts=tuple(
                    debian_relation(item, f"{label} conflict") for item in output.conflicts
                ),
                provides=tuple(
                    debian_relation(item, f"{label} provide") for item in output.provides
                ),
                replaces=tuple(
                    debian_relation(item, f"{label} replace") for item in output.replaces
                ),
                conffiles=tuple(sorted("/" + item for item in output.backup)),
                scripts=_scripts(output, runtime),
                changelog_entry=(
                    f"Build {runtime.product.display_name} {runtime.product.version} "
                    f"for {release.distribution} {release.version}."
                ),
                codename=release.codename,
            )
        )
    check_edition_contract(plans, outputs, target)
    return tuple(plans)


def check_edition_contract(
    plans: list,
    outputs: tuple[SplitOutput, ...],
    target: DistributionTarget,
) -> None:
    """Fail unless each edition's packages declare exactly its catalog contract.

    Plans of either package format expose `package_name`, `depends`,
    `conflicts`, `provides` and `replaces` in the target's own relation syntax.
    """

    names = {plan.package_name for plan in plans}
    for edition, component in target.components.items():
        members = [
            plan
            for plan, output in zip(plans, outputs, strict=True)
            if output.edition == edition
        ]
        external = {
            item for plan in members for item in plan.depends if relation_name(item) not in names
        }
        if external != set(component.dependencies):
            raise ModelError(
                f"{target.id} {edition}: package dependencies differ from the edition "
                f"contract: expected {sorted(component.dependencies)}, found {sorted(external)}"
            )
        conflicts = {item for plan in members for item in plan.conflicts}
        if conflicts != set(component.conflicts):
            raise ModelError(f"{target.id} {edition}: package conflicts differ from the edition")
        if any(plan.provides or plan.replaces for plan in members) and not (
            component.provides or component.replaces
        ):
            raise ModelError(f"{target.id} {edition}: packages may not provide or replace")


def control_text(plan: DebianPlan, installed_size: int) -> str:
    lines = [
        f"Package: {plan.package_name}",
        f"Version: {plan.version}",
        f"Architecture: {plan.architecture}",
        f"Maintainer: {DEBIAN_MAINTAINER}",
        f"Installed-Size: {installed_size}",
        f"Depends: {', '.join(plan.depends)}",
    ]
    for field, values in (
        ("Suggests", plan.suggests),
        ("Conflicts", plan.conflicts),
        ("Provides", plan.provides),
        ("Replaces", plan.replaces),
    ):
        if values:
            lines.append(f"{field}: {', '.join(values)}")
    lines.extend(
        [
            f"Section: {plan.section}",
            "Priority: optional",
            f"Homepage: {plan.homepage}",
            f"Description: {plan.synopsis}",
            *(f" {line}" for line in plan.extended_description),
            "",
        ]
    )
    return "\n".join(lines)


def _dep5(plan: DebianPlan, license_id: str) -> str:
    if license_id not in DEP5_LICENSES or license_id not in LICENSE_PARAGRAPHS:
        raise ModelError(f"{plan.package_name}: no Debian license paragraph for {license_id}")
    return DEP5_LICENSES[license_id]


def copyright_text(plan: DebianPlan) -> str:
    lines = [
        "Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/",
        "Upstream-Name: hyperflux-next",
        f"Source: {plan.homepage}",
        "",
        "Files: *",
        f"Copyright: {COPYRIGHT_HOLDER}",
        f"License: {' and '.join(_dep5(plan, item) for item in plan.licenses)}",
    ]
    for license_id in plan.licenses:
        paragraph = LICENSE_PARAGRAPHS[license_id]
        lines.extend(["", f"License: {_dep5(plan, license_id)}", *(f" {line}" for line in paragraph)])
    lines.append("")
    return "\n".join(lines)


def changelog_bytes(plan: DebianPlan, epoch: int) -> bytes:
    date = format_datetime(datetime.fromtimestamp(epoch, timezone.utc))
    text = "\n".join(
        [
            f"{plan.package_name} ({plan.version}) {plan.codename}; urgency=medium",
            "",
            f"  * {plan.changelog_entry}",
            "",
            f" -- {DEBIAN_MAINTAINER}  {date}",
            "",
        ]
    ).encode("utf-8")
    buffer = io.BytesIO()
    # No file name and a zero timestamp, as `gzip -9n` writes them.
    with gzip.GzipFile(filename="", mode="wb", compresslevel=9, fileobj=buffer, mtime=0) as stream:
        stream.write(text)
    return buffer.getvalue()


def md5sums(root: Path) -> str:
    lines = []
    for path in tree_files(root):
        relative = path.relative_to(root).as_posix()
        if relative.startswith("DEBIAN/"):
            continue
        digest = hashlib.md5(path.read_bytes(), usedforsecurity=False).hexdigest()
        lines.append(f"{digest}  {relative}")
    return "\n".join(lines) + "\n"


def installed_size(root: Path) -> int:
    """Kibibytes as dpkg-gencontrol counts them: files rounded up, one per directory."""

    total = 0
    for path in root.rglob("*"):
        if path.relative_to(root).parts[0] == "DEBIAN":
            continue
        total += (path.stat().st_size + 1023) // 1024 if path.is_file() else 1
    return max(1, total)


def _is_elf(path: Path) -> bool:
    with path.open("rb") as stream:
        return stream.read(4) == b"\x7fELF"


def c_runtime_requirements(path: Path) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """Highest GLIBC symbol version an ELF file needs: (strong, any).

    Weak references (for example `pidfd_spawnp`) resolve to null on an older
    glibc, so only strong references set the hard floor.
    """

    try:
        result = subprocess.run(
            ["objdump", "-T", str(path)],
            check=False,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=60,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise ModelError(f"cannot read dynamic symbols of {path.name}: {error}") from error
    if result.returncode != 0:
        raise ModelError(f"cannot read dynamic symbols of {path.name}: {result.stderr.strip()}")
    return glibc_requirements(result.stdout, path.name)


def glibc_requirements(symbols: str, label: str) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """Parse `objdump -T` output into the highest (strong, any) GLIBC version.

    The flag column starts at offset 17; a `w` at offset 18 marks a weak
    reference.
    """

    strong: tuple[int, ...] = ()
    every: tuple[int, ...] = ()
    for line in symbols.splitlines():
        if "*UND*" not in line:
            continue
        match = GLIBC_SYMBOL.search(line)
        if match is None:
            continue
        name = match.group("version") or match.group("bare")
        if not re.fullmatch(r"GLIBC_[0-9]+(?:\.[0-9]+)+", name):
            raise ModelError(f"{label} needs the private glibc interface {name}")
        version = tuple(int(part) for part in name.removeprefix("GLIBC_").split("."))
        every = max(every, version)
        weak = len(line) > 18 and line[18] == "w"
        if not weak:
            strong = max(strong, version)
    return strong, every


def check_c_runtime(root: Path, target: DistributionTarget) -> tuple[str, ...]:
    """Fail unless every ELF file runs on the target release's glibc.

    Strong symbol versions must not exceed the declared `libc6 (>= floor)`;
    no symbol version may exceed the release glibc. Returns the ELF paths.
    """

    if target.release is None:
        raise ModelError(f"distribution {target.id}: no release C runtime to check against")
    floor = version_key(c_runtime_floor(target))
    ceiling = version_key(target.release.c_runtime_version)
    checked = []
    for path in tree_files(root):
        if not _is_elf(path):
            continue
        relative = path.relative_to(root).as_posix()
        strong, every = c_runtime_requirements(path)
        if strong > floor:
            raise ModelError(
                f"{relative} needs glibc {'.'.join(map(str, strong))}, above the declared "
                f"floor {'.'.join(map(str, floor))}"
            )
        if every > ceiling:
            raise ModelError(
                f"{relative} references glibc {'.'.join(map(str, every))}, above "
                f"{target.release.distribution} {target.release.version}"
            )
        checked.append(relative)
    return tuple(checked)


def _write_control_files(plan: DebianPlan, root: Path, epoch: int) -> dict[str, bytes]:
    control = root / "DEBIAN"
    control.mkdir(mode=0o755)
    content: dict[str, str] = {
        "control": control_text(plan, installed_size(root)),
        "md5sums": md5sums(root),
        **dict(plan.scripts),
    }
    if plan.conffiles:
        content["conffiles"] = "".join(f"{item}\n" for item in plan.conffiles)
    written: dict[str, bytes] = {}
    for name, value in sorted(content.items()):
        path = control / name
        payload = value.encode("utf-8")
        path.write_bytes(payload)
        path.chmod(0o755 if name in SCRIPT_NAMES else 0o644)
        os.utime(path, (epoch, epoch))
        written[name] = payload
    control.chmod(0o755)
    os.utime(control, (epoch, epoch))
    return written


def _add_documentation(plan: DebianPlan, root: Path, epoch: int) -> dict[str, bytes]:
    directory = root.joinpath(*plan.doc_directory.parts)
    if directory.exists():
        raise ModelError(f"{plan.package_name}: the staged payload already owns {plan.doc_directory}")
    directory.mkdir(parents=True)
    documents = {
        "copyright": copyright_text(plan).encode("utf-8"),
        "changelog.Debian.gz": changelog_bytes(plan, epoch),
    }
    for name, content in documents.items():
        path = directory / name
        path.write_bytes(content)
        path.chmod(0o644)
    return {f"{plan.doc_directory}/{name}": content for name, content in documents.items()}


def _run_dpkg_deb(root: Path, package: Path, epoch: int) -> None:
    environment = dict(os.environ)
    environment["SOURCE_DATE_EPOCH"] = str(epoch)
    try:
        result = subprocess.run(
            [
                "dpkg-deb",
                "--build",
                "--root-owner-group",
                "--uniform-compression",
                "--threads-max=1",
                "-Zxz",
                "-z9",
                str(root),
                str(package),
            ],
            env=environment,
            check=False,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=300,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise ModelError(f"Debian package build failed: {error}") from error
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise ModelError(
            f"Debian package build failed with exit status {result.returncode}: {detail}"
        )


def _dpkg_tar(package: Path, option: str) -> bytes:
    try:
        result = subprocess.run(
            ["dpkg-deb", option, str(package)],
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise ModelError(f"cannot inspect Debian package: {error}") from error
    if result.returncode != 0:
        raise ModelError(
            f"cannot inspect Debian package with {option}: exit status {result.returncode}"
        )
    return result.stdout


def _member_name(member: tarfile.TarInfo) -> str:
    return PurePosixPath(member.name.removeprefix("./")).as_posix()


def parse_control(content: bytes) -> dict[str, str]:
    fields: dict[str, str] = {}
    current = None
    for line in content.decode("utf-8").splitlines():
        if line.startswith(" ") and current is not None:
            fields[current] += "\n" + line
            continue
        key, separator, value = line.partition(": ")
        if not separator or not re.fullmatch(r"[A-Za-z][A-Za-z0-9-]*", key) or key in fields:
            raise ModelError("Debian control file is malformed")
        fields[key] = value
        current = key
    return fields


