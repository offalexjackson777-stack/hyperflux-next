from __future__ import annotations

from typing import Any

from ..documentation import DocumentCatalog
from ..model import ModelError


INDEX_PATH = "docs/generated/README.md"


def _terms(profiles: dict[str, Any]) -> list[tuple[str, str]]:
    scope = profiles["official_receiver_scope"]
    receiver = f"{scope['vendor_id']:04X}:{scope['receiver_product_id']:04X}"
    surfaces = sorted(
        (profile for profile in profiles["profiles"] if profile["kind"] == "surface"),
        key=lambda profile: profile["profile_id"],
    )
    if [profile["identity"]["variant_key"] for profile in surfaces] != ["hard-edition"]:
        raise ModelError("generated index: surface terms assume one Hard Edition profile")
    hard = surfaces[0]["profile_id"]
    return [
        (
            "Receiver",
            f"The HyperFlux V2 USB receiver, exact `{receiver}`. "
            "Every HyperFlux command to a wireless device goes through it.",
        ),
        (
            "Child",
            "A wireless mouse or keyboard that HyperFlux reaches through the receiver, "
            "identified by its wireless product ID.",
        ),
        (
            "Mat",
            "The HyperFlux V2 charging mat, device kind `mat`. HyperFlux does not control "
            "the mat itself.",
        ),
        (
            "Hard Edition",
            f"The hard-surface version of the mat, with the profile `{hard}`.",
        ),
        (
            "Cloth Edition",
            "The cloth-surface version of the mat. It has no profile, has not been "
            "tested on real hardware, and HyperFlux does not guess its USB ID.",
        ),
        (
            "Route",
            "One tested path from one of your apps to one device through the receiver.",
        ),
        (
            "Compatibility snapshot",
            f"The official Razer compatibility list `{scope['snapshot_id']}`. HyperFlux "
            "only considers devices on this list.",
        ),
        (
            "Support tier",
            "Tested on real hardware, expected to work, or not supported yet, as "
            "defined in [Supported Hardware](supported-hardware.md).",
        ),
    ]


def markdown(catalog: DocumentCatalog, profiles: dict[str, Any]) -> str:
    pages = sorted(
        (
            document
            for document in catalog.documents
            if document.path.startswith("docs/generated/") and document.path != INDEX_PATH
        ),
        key=lambda document: document.title,
    )
    if not pages:
        raise ModelError("generated index: no generated pages are catalogued")
    lines = [
        "# Generated Reference",
        "",
        "> Generated by `./hfx generate`. Do not edit manually.",
        "",
        "This page lists every reference page that is built from the project's data files, for anyone looking up exact facts such as supported devices, error codes, or package contents.",
        "",
        "To change a page, change the file it is generated from and run `./hfx generate`;",
        "never edit a page directly. For guides, start at the",
        "[documentation hub](../README.md).",
        "",
        "## Terms",
        "",
        "These terms mean the same thing on every generated page.",
        "",
        "| Term | Meaning |",
        "| --- | --- |",
        *(f"| {term} | {meaning} |" for term, meaning in _terms(profiles)),
        "",
        "## Pages",
        "",
        "| Page | What it lists | Generated from |",
        "| --- | --- | --- |",
    ]
    for document in pages:
        name = document.path.removeprefix("docs/generated/")
        sources = ", ".join(f"`{source}`" for source in document.canonical_sources)
        lines.append(f"| [{document.title}]({name}) | {document.purpose} | {sources} |")
    return "\n".join(lines) + "\n"
