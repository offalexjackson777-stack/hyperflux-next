def driver_preflight_service(
    deployment: OpenRazerNativeDeployment, runtime: LinuxRuntime
) -> str:
    relay = deployment.relay
    bridge = runtime.bridge
    private_directory = PurePosixPath(runtime.operations.activation_path).parent
    metadata_commands = len(deployment.driver.modules) + len(
        deployment.compatibility.runtime_capability.modules
    )
    metadata_timeout_ms = metadata_commands * runtime.operations.status_timeout_ms
    if metadata_timeout_ms >= DRIVER_PREFLIGHT_TIMEOUT_SECONDS * 1_000:
        raise ModelError(
            "OpenRazer driver metadata command budget exceeds its service timeout"
        )
    return "\n".join(
        [
            "# Generated by ./hfx generate. Do not edit manually.",
            "# SPDX-License-Identifier: GPL-2.0-only",
            "[Unit]",
            "Description=HyperFlux Next OpenRazer driver metadata preflight",
            f"PartOf={bridge.service_unit}",
            f"Before={relay.service_unit}",
            f"After={bridge.service_unit} systemd-udevd.service",
            "",
            "[Service]",
            "Type=oneshot",
            "DynamicUser=yes",
            f"ExecStart={runtime.operations.activation_path} check-openrazer-driver",
            "UMask=0077",
            "Restart=no",
            f"TimeoutStartSec={DRIVER_PREFLIGHT_TIMEOUT_SECONDS}s",
            "NoNewPrivileges=yes",
            "ProtectSystem=strict",
            "ProtectHome=yes",
            "PrivateTmp=yes",
            "PrivateDevices=yes",
            "ProtectControlGroups=yes",
            "ProtectKernelTunables=yes",
            "ProtectKernelModules=no",
            "ProtectKernelLogs=yes",
            "ProtectHostname=yes",
            "ProtectClock=yes",
            "RestrictAddressFamilies=none",
            "RestrictNamespaces=yes",
            "RestrictRealtime=yes",
            "RestrictSUIDSGID=yes",
            "LockPersonality=yes",
            "MemoryDenyWriteExecute=yes",
            "SystemCallArchitectures=native",
            "SystemCallFilter=@system-service",
            "SystemCallFilter=~@mount @module @raw-io @reboot @swap",
            "CapabilityBoundingSet=",
            "AmbientCapabilities=",
            "DevicePolicy=closed",
            f"InaccessiblePaths={bridge.runtime_directory}",
            f"ReadOnlyPaths={private_directory} /usr/lib/modules",
            "",
        ]
    )


