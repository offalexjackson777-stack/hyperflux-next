DRIVER_PREFLIGHT_TIMEOUT_SECONDS = 10
HID_DRIVER_ROOT = "/sys/bus/hid/drivers"


def _key_event_receivers(
    deployment: OpenRazerNativeDeployment, profiles: dict[str, Any]
) -> list[tuple[int, int, int, str]]:
    """Resolve each key-event link to its receiver USB identity and interface."""

    receivers = {
        profile["profile_id"]: profile["identity"]
        for profile in profiles["profiles"]
        if profile["kind"] == "receiver"
    }
    resolved: list[tuple[int, int, int, str]] = []
    for link in deployment.key_events.links:
        identity = receivers.get(link.receiver_profile_id)
        if identity is None or identity.get("authority") != "usb":
            raise ModelError(
                f"OpenRazer key-event link {link.link_name} names no USB receiver profile"
            )
        resolved.append(
            (
                identity["vendor_id"],
                identity["product_id"],
                link.receiver_usb_interface,
                link.link_name,
            )
        )
    return resolved


