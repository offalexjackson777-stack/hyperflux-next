from __future__ import annotations

import json
from pathlib import PurePosixPath

from ..linux_runtime import LinuxRuntime
from ..openrazer_native_route import OpenRazerNativeDeployment


def rust_constants(deployment: OpenRazerNativeDeployment) -> str:
    driver = deployment.driver
    compatibility = deployment.compatibility
    capability = compatibility.runtime_capability
    modules = ", ".join(json.dumps(module) for module in driver.modules)
    capability_modules = ", ".join(
        json.dumps(module) for module in capability.modules
    )
    return "\n".join(
        [
            "// Generated by ./hfx generate. Do not edit manually.",
            "// SPDX-License-Identifier: GPL-2.0-only",
            "",
            "pub const OPENRAZER_NATIVE_DEPLOYMENT_SHA256: &str =",
            f"    {json.dumps(deployment.source_sha256)};",
            f"pub const OPENRAZER_NATIVE_DKMS_NAME: &str = {json.dumps(driver.dkms_name)};",
            f"pub const OPENRAZER_NATIVE_DKMS_VERSION: &str = {json.dumps(driver.dkms_version)};",
            "pub const OPENRAZER_NATIVE_DRIVER_MODULES: &[&str] =",
            f"    &[{modules}];",
            "pub const OPENRAZER_NATIVE_CAPABILITY_MODULES: &[&str] = "
            f"&[{capability_modules}];",
            "pub const OPENRAZER_NATIVE_CAPABILITY_FIELD: &str = "
            f"{json.dumps(capability.modinfo_field)};",
            "pub const OPENRAZER_NATIVE_CAPABILITY_VALUE: &str = "
            f"{json.dumps(capability.expected_value)};",
            "pub const OPENRAZER_NATIVE_VERIFIED_UPSTREAM_VERSION: &str = "
            f"{json.dumps(compatibility.verified_upstream_version)};",
            "pub const OPENRAZER_NATIVE_DAEMON_EXECUTABLE_PATH: &str = "
            f"{json.dumps(compatibility.daemon_executable_path)};",
            "pub const OPENRAZER_NATIVE_VERSION_ARGUMENT: &str = "
            f"{json.dumps(compatibility.version_argument)};",
            "",
        ]
    )


def relay_service(
    deployment: OpenRazerNativeDeployment, runtime: LinuxRuntime
) -> str:
    relay = deployment.relay
    bridge = runtime.bridge
    private_directory = PurePosixPath(relay.executable_path).parent
    return "\n".join(
        [
            "# Generated by ./hfx generate. Do not edit manually.",
            "# SPDX-License-Identifier: GPL-2.0-only",
            "[Unit]",
            "Description=HyperFlux Next OpenRazer native-route relay",
            f"PartOf={bridge.service_unit}",
            f"Requires={bridge.service_unit}",
            f"After={bridge.service_unit} systemd-udevd.service",
            f"ConditionPathExists={relay.uhid_device}",
            "",
            "[Service]",
            "Type=simple",
            "User=root",
            "Group=root",
            f"ExecCondition={runtime.operations.activation_path} check-openrazer-runtime",
            f"ExecStart={relay.executable_path} --socket {bridge.socket_path} "
            f"--uhid {relay.uhid_device}",
            "UMask=0077",
            "Restart=on-failure",
            f"RestartSec={relay.restart_seconds}s",
            "TimeoutStartSec=10s",
            "TimeoutStopSec=10s",
            "LimitNOFILE=64",
            "TasksMax=32",
            "NoNewPrivileges=yes",
            "ProtectSystem=strict",
            "ProtectHome=yes",
            "PrivateTmp=yes",
            "ProtectControlGroups=yes",
            "ProtectKernelTunables=yes",
            "ProtectKernelModules=yes",
            "ProtectKernelLogs=yes",
            "ProtectHostname=yes",
            "ProtectClock=yes",
            "RestrictAddressFamilies=AF_UNIX",
            "RestrictNamespaces=yes",
            "RestrictRealtime=yes",
            "RestrictSUIDSGID=yes",
            "LockPersonality=yes",
            "MemoryDenyWriteExecute=yes",
            "SystemCallArchitectures=native",
            "SystemCallFilter=@system-service",
            "SystemCallFilter=~@mount @module @raw-io @reboot @swap",
            "CapabilityBoundingSet=",
            "AmbientCapabilities=",
            "DevicePolicy=closed",
            f"DeviceAllow={relay.uhid_device} rw",
            f"ReadOnlyPaths={private_directory} {bridge.runtime_directory}",
            f"ReadWritePaths={relay.uhid_device}",
            "",
        ]
    )


def sysusers(deployment: OpenRazerNativeDeployment) -> str:
    return "\n".join(
        [
            "# Generated by ./hfx generate. Do not edit manually.",
            "# SPDX-License-Identifier: GPL-2.0-only",
            f"g {deployment.access.group} -",
            "",
        ]
    )


def markdown(deployment: OpenRazerNativeDeployment, runtime: LinuxRuntime) -> str:
    relay = deployment.relay
    driver = deployment.driver
    access = deployment.access
    compatibility = deployment.compatibility
    capability = compatibility.runtime_capability
    return "\n".join(
        [
            "# OpenRazer Native Route Deployment",
            "",
            "> Generated by `./hfx generate`. Do not edit manually.",
            "",
            f"Canonical deployment digest: `{deployment.source_sha256}`.",
            "",
            "## Relay",
            "",
            "| Field | Value |",
            "| --- | --- |",
            f"| Service | `{relay.service_unit}` |",
            f"| Executable | `{relay.executable_path}` |",
            f"| Bridge socket | `{runtime.bridge.socket_path}` |",
            f"| Exclusive kernel interface | `{relay.uhid_device}` |",
            "",
            "The static relay service is pulled in by the bridge service. It runs as root only "
            "because `/dev/uhid` remains unavailable to ordinary users, drops every Linux "
            "capability, and can access only the bridge socket and UHID device. The bridge's "
            "start-preparation unit performs the read-only transformed-driver preflight before "
            "this sealed relay namespace is entered.",
            "",
            "## OpenRazer Driver Replacement",
            "",
            "| Field | Value |",
            "| --- | --- |",
            f"| DKMS identity | `{driver.dkms_name}` `{driver.dkms_version}` |",
            f"| Source tree | `{driver.source_directory}` |",
            f"| Modules | {', '.join(f'`{module}`' for module in driver.modules)} |",
            "",
            "The package build applies the source-locked transport patch to the pinned OpenRazer "
            "tree, projects only its DKMS build inputs, and verifies every transformed digest. "
            "The ordinary BUS_USB tables and direct-device transport remain upstream-owned.",
            "",
            "## Update Compatibility",
            "",
            "| Field | Value |",
            "| --- | --- |",
            f"| Verified upstream source | `{compatibility.verified_upstream_version}` |",
            f"| Package release suffix | `{compatibility.package_release_policy}` |",
            f"| New upstream source | `{compatibility.unverified_upstream_policy}` |",
            f"| Runtime capability | `{capability.modinfo_field}={capability.expected_value}` |",
            f"| Capability modules | {', '.join(f'`{module}`' for module in capability.modules)} |",
            "",
            "Runtime readiness is determined from the declared module capability and installed/loaded "
            "module identities, not from a distribution package-release suffix. The daemon's upstream "
            "source version is checked separately as verification lineage: packaging revisions of the "
            "verified source remain compatible, while a new upstream source requires a reviewed rebase "
            "and fresh verification.",
            "",
            "## Local Access",
            "",
            "| Field | Value |",
            "| --- | --- |",
            f"| Group | `{access.group}` |",
            f"| Udev rules | `{access.udev_rules_path}` |",
            f"| Mount helper | `{access.mount_helper_path}` |",
            f"| Sysusers declaration | `{access.sysusers_path}` |",
            "",
            "The rules and helper are selected from the same transformed, pinned OpenRazer "
            "tree as the DKMS source. The package manager owns every deployed file, and the "
            "distribution group substitution is part of the reviewed source transform.",
            "",
        ]
    )
