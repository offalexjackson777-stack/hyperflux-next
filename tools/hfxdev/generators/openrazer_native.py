def key_event_udev_rules(
    deployment: OpenRazerNativeDeployment, profiles: dict[str, Any]
) -> str:
    end_label = "hyperflux_next_openrazer_keys_end"
    lines = [
        "# Generated by ./hfx generate. Do not edit manually.",
        "# SPDX-License-Identifier: GPL-2.0-only",
        "# OpenRazer reads a keyboard's key presses for reactive effects such as",
        "# Ripple from a /dev/input/by-id name it matches once, when it adds the",
        "# device. Each line adds that name on the receiver interface that carries",
        "# the paired keyboard's key presses and gives the logged-in seat user",
        "# access to it. The uaccess tag only works before 73-seat-late.rules.",
        f'ACTION=="remove", GOTO="{end_label}"',
        f'SUBSYSTEM!="input", GOTO="{end_label}"',
        f'KERNEL!="event*", GOTO="{end_label}"',
    ]
    for vendor, product, interface, name in _key_event_receivers(deployment, profiles):
        lines.append(
            f'ENV{{ID_BUS}}=="usb", ENV{{ID_VENDOR_ID}}=="{vendor:04x}", '
            f'ENV{{ID_MODEL_ID}}=="{product:04x}", '
            f'ENV{{ID_USB_INTERFACE_NUM}}=="{interface:02x}", '
            f'SYMLINK+="input/by-id/{name}", TAG+="uaccess"'
        )
    lines.extend([f'LABEL="{end_label}"', ""])
    return "\n".join(lines)


def relay_service(
    deployment: OpenRazerNativeDeployment, runtime: LinuxRuntime
) -> str:
    relay = deployment.relay
    bridge = runtime.bridge
    private_directory = PurePosixPath(relay.executable_path).parent
    # REL-020: the relay unbinds the OpenRazer driver from its own virtual
    # device before UHID_DESTROY, so each driver's unbind file stays writable
    # under ProtectKernelTunables. A driver that is not loaded is skipped.
    driver_unbind_paths = " ".join(
        f"-{HID_DRIVER_ROOT}/{module}/unbind" for module in deployment.driver.modules
    )
    return "\n".join(
        [
            "# Generated by ./hfx generate. Do not edit manually.",
            "# SPDX-License-Identifier: GPL-2.0-only",
            "[Unit]",
            "Description=HyperFlux Next OpenRazer native-route relay",
            f"PartOf={bridge.service_unit}",
            f"Requires={bridge.service_unit} {relay.preflight_service_unit}",
            f"After={bridge.service_unit} {relay.preflight_service_unit} systemd-udevd.service",
            "Before=systemd-user-sessions.service",
            f"ConditionPathExists={relay.uhid_device}",
            f"ConditionFileIsExecutable={deployment.compatibility.daemon_executable_path}",
            "",
            "[Service]",
            "Type=simple",
            "User=root",
            "Group=root",
            f"SupplementaryGroups={bridge.client_group}",
            f"ExecStart={relay.executable_path} --socket {bridge.socket_path} "
            f"--uhid {relay.uhid_device} "
            "--status /run/hyperflux-next-openrazer-relay/status.json",
            "UMask=0077",
            "RuntimeDirectory=hyperflux-next-openrazer-relay",
            "RuntimeDirectoryMode=0755",
            "Restart=no",
            "TimeoutStartSec=10s",
            "TimeoutStopSec=10s",
            "LimitNOFILE=64",
            "TasksMax=32",
            "NoNewPrivileges=yes",
            "ProtectSystem=strict",
            "ProtectHome=yes",
            "PrivateTmp=yes",
            "ProtectControlGroups=yes",
            "ProtectKernelTunables=yes",
            "ProtectKernelModules=yes",
            "ProtectKernelLogs=yes",
            "ProtectHostname=yes",
            "ProtectClock=yes",
            "RestrictAddressFamilies=AF_UNIX",
            "RestrictNamespaces=yes",
            "RestrictRealtime=yes",
            "RestrictSUIDSGID=yes",
            "LockPersonality=yes",
            "MemoryDenyWriteExecute=yes",
            "SystemCallArchitectures=native",
            "SystemCallFilter=@system-service",
            "SystemCallFilter=~@mount @module @raw-io @reboot @swap",
            "CapabilityBoundingSet=",
            "AmbientCapabilities=",
            "DevicePolicy=closed",
            f"DeviceAllow={relay.uhid_device} rw",
            f"ReadOnlyPaths={private_directory} {bridge.runtime_directory}",
            f"ReadWritePaths={relay.uhid_device} /run/hyperflux-next-openrazer-relay",
            f"ReadWritePaths={driver_unbind_paths}",
            "",
        ]
    )


