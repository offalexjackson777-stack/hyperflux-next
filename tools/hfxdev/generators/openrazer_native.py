DRIVER_PREFLIGHT_TIMEOUT_SECONDS = 10


def rust_constants(deployment: OpenRazerNativeDeployment) -> str:
    driver = deployment.driver
    relay = deployment.relay
    compatibility = deployment.compatibility
    capability = compatibility.runtime_capability
    modules = ", ".join(json.dumps(module) for module in driver.modules)
    capability_modules = ", ".join(
        json.dumps(module) for module in capability.modules
    )
    return "\n".join(
        [
            "// Generated by ./hfx generate. Do not edit manually.",
            "// SPDX-License-Identifier: GPL-2.0-only",
            "",
            "pub const OPENRAZER_NATIVE_DEPLOYMENT_SHA256: &str =",
            f"    {json.dumps(deployment.source_sha256)};",
            "pub const OPENRAZER_NATIVE_UPSTREAM_COMMIT: &str = "
            f"{json.dumps(deployment.upstream_commit)};",
            f"pub const OPENRAZER_NATIVE_DKMS_NAME: &str = {json.dumps(driver.dkms_name)};",
            f"pub const OPENRAZER_NATIVE_DKMS_VERSION: &str = {json.dumps(driver.dkms_version)};",
            "pub const OPENRAZER_NATIVE_DRIVER_MODULES: &[&str] =",
            f"    &[{modules}];",
            "pub const OPENRAZER_NATIVE_CAPABILITY_MODULES: &[&str] = "
            f"&[{capability_modules}];",
            "pub const OPENRAZER_NATIVE_CAPABILITY_FIELD: &str = "
            f"{json.dumps(capability.modinfo_field)};",
            "pub const OPENRAZER_NATIVE_CAPABILITY_VALUE: &str = "
            f"{json.dumps(capability.expected_value)};",
            "pub const OPENRAZER_NATIVE_VERIFIED_UPSTREAM_VERSION: &str = "
            f"{json.dumps(compatibility.verified_upstream_version)};",
            "pub const OPENRAZER_NATIVE_DAEMON_EXECUTABLE_PATH: &str = "
            f"{json.dumps(compatibility.daemon_executable_path)};",
            "pub const OPENRAZER_NATIVE_VERSION_ARGUMENT: &str = "
            f"{json.dumps(compatibility.version_argument)};",
            "pub const OPENRAZER_NATIVE_RELAY_SERVICE_UNIT: &str = "
            f"{json.dumps(relay.service_unit)};",
            "pub const OPENRAZER_NATIVE_DRIVER_PREFLIGHT_SERVICE_UNIT: &str =",
            f"    {json.dumps(relay.preflight_service_unit)};",
            "",
        ]
    )


