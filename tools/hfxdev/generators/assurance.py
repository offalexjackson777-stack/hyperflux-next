from __future__ import annotations

from collections import Counter
import re

from ..assurance import DesignCoverageEntry
from ..release import ReleaseTarget


PHYSICAL_EVIDENCE_PREFIXES = ("evidence/", "profiles/evidence/")


def _physical(entry: DesignCoverageEntry) -> str:
    if not entry.physical_evidence_required:
        return "not needed"
    if any(path.startswith(PHYSICAL_EVIDENCE_PREFIXES) for path in entry.evidence):
        return "retained"
    return "none retained"


def _anchor(entry: DesignCoverageEntry) -> str:
    value = re.sub(r"[^\w\- ]", "", f"{entry.section}. {entry.title}".lower())
    return value.replace(" ", "-")


def design_coverage_markdown(
    entries: tuple[DesignCoverageEntry, ...], release: ReleaseTarget
) -> str:
    counts = Counter(entry.status for entry in entries)
    lines = [
        "# Design Coverage",
        "",
        "> Generated by `./hfx generate`. Do not edit manually.",
        "",
        "This page summarizes the current Design Book coverage. The complete per-section evidence",
        "map remains in [`assurance/design-coverage.json`](../../assurance/design-coverage.json).",
        "Software verification never substitutes for physical evidence.",
        "",
        f"Release `{release.product_version}-{release.package_release}` is `{release.state}`.",
        "No section blocks it; the open items below are limitations or future work.",
        "",
        "## Summary",
        "",
    ]
    for status in sorted(counts):
        lines.append(f"- `{status}`: {counts[status]}")
    lines.extend(
        [
            "",
            "",
            "## Limitations And Future Work",
            "",
            "Only sections with a limitation, future work, or a non-complete status are listed here.",
            "Physical evidence is `retained` when the section cites a retained hardware record.",
            "",
            "| Section | Subject | Status | Owner | Physical evidence | Limitation or future work |",
            "| ---: | --- | --- | --- | --- | --- |",
        ]
    )
    visible = tuple(
        entry
        for entry in entries
        if entry.remaining or entry.status != "software-verified"
    )
    for entry in visible:
        remaining = " ".join(entry.remaining) if entry.remaining else "None."
        lines.append(
            f"| {entry.section} | [{entry.title}](../{entry.chapter.removeprefix('docs/')}#"
            f"{_anchor(entry)}) | `{entry.status}` | "
            f"`{entry.owner}` | {_physical(entry)} | {remaining} |"
        )
    lines.extend(
        [
            "",
            "## Reading The Complete Record",
            "",
            "- Read the [Design Book](../architecture/design-book.md) for implemented architecture and rationale.",
            "- Inspect [`assurance/design-coverage.json`](../../assurance/design-coverage.json) for every section, evidence path, owner, and status.",
            "- Read [release gates](release-gates.md) for the smaller set of product-level checks.",
        ]
    )
    return "\n".join(lines) + "\n"
