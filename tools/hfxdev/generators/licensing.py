from __future__ import annotations

from typing import Any


def markdown(policy: dict[str, Any]) -> str:
    rows = "\n".join(
        f"| `{rule['path']}` | `{rule['expression']}` | {rule['reason']} |"
        for rule in policy["rules"]
    )
    texts = "\n".join(
        f"- `{expression}`: [`{path}`](../../{path})"
        for expression, path in sorted(policy["license_texts"].items())
    )
    return f"""# Licensing

> Generated by `./hfx generate` from `governance/licensing.json`. Do not edit manually.

This page lists the license of every part of HyperFlux, for anyone who wants to
reuse, package, or contribute code.

{policy['rationale']}

The project license is `GPL-2.0-only`, and it is the only license at the root of
the repository. A few paths use a different license, listed below.

## License By Path

| Path | SPDX expression | Reason |
| --- | --- | --- |
{rows}

## License Texts

{texts}

The project checks compare every source file that has an SPDX header with this
table. Code copied from elsewhere must also record where it came from, the
exact version, its license, and how it was changed.
"""
