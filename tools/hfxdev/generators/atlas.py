def collection_readme(atlas: RepositoryAtlas, path: str) -> str:
    children = tuple(node for node in atlas.nodes if node.path.startswith(path + "/"))
    subcollections = tuple(
        sorted(
            item
            for item in COLLECTION_TITLES
            if item.startswith(path + "/") and "/" not in item.removeprefix(path + "/")
        )
    )
    owners: dict[str, tuple[int, int]] = {}
    for node in atlas.nodes:
        canonical = sum(item.startswith(path + "/") for item in node.canonical_files)
        generated = sum(
            item.startswith(path + "/") and item != f"{path}/README.md"
            for item in node.generated_files
        )
        if canonical or generated:
            owners[node.id] = (canonical, generated)
    if path == "LICENSES" and "governance" not in owners:
        owners["governance"] = (1, 0)

    lines = [
        f"# {COLLECTION_TITLES.get(path, path.title())}",
        "",
        GENERATED_NOTICE,
        "",
        COLLECTION_PURPOSES.get(
            path,
            "This folder groups related source files and the files generated from them.",
        ),
        "",
    ]
    if children or subcollections:
        lines.extend(
            [
                "## What Is Inside",
                "",
                "| Area | Purpose |",
                "| --- | --- |",
            ]
        )
        for item in subcollections:
            lines.append(
                f"| {_link(path, item + '/README.md', COLLECTION_TITLES[item])} | {COLLECTION_PURPOSES[item]} |"
            )
        for node in children:
            lines.append(
                f"| {_link(path, node.path + '/README.md', node.title)} | {node.purpose} |"
            )
        lines.append("")
    if owners:
        lines.extend(
            [
                "## Who Owns These Files",
                "",
                "| Owner | Source files | Generated files |",
                "| --- | ---: | ---: |",
            ]
        )
        for identifier, (canonical, generated) in sorted(owners.items()):
            node = atlas.by_id[identifier]
            lines.append(
                f"| {_link(path, node.path + '/README.md', node.title)} | {canonical} | {generated} |"
            )
        lines.append("")
    lines.extend(
        [
            "## Change Workflow",
            "",
            "1. Open the area that owns the file, listed above.",
            "2. Change its source file, not a generated file.",
            "3. Run `./hfx generate` from the repository root.",
            "4. Run the checks listed in that area's README.",
        ]
    )
    return "\n".join(lines) + "\n"


def markdown(atlas: RepositoryAtlas) -> str:
    categories = sorted({node.category for node in atlas.nodes})
    lines = [
        "# Repository Atlas",
        "",
        GENERATED_NOTICE,
        "",
        "Maintainer reference for repository ownership. It lists every part of the repository with its status, purpose, and what it depends on, for maintainers who need to know who owns a file. To learn how HyperFlux works, start with the [architecture overview](../developer/architecture.md) instead.",
        "",
        "The full list of files each part owns is in [`architecture/repository-atlas.json`](../../architecture/repository-atlas.json).",
        "",
        f"- **Parts:** {len(atlas.nodes)}",
        f"- **Categories:** {len(categories)}",
        f"- **Release state:** `{atlas.publication_state}`",
        "",
        "## Browse By Area",
        "",
        "| Area | Parts |",
        "| --- | --- |",
    ]
    for category in categories:
        links = ", ".join(
            f"[{node.title}](../../{node.path}/README.md)"
            for node in atlas.nodes
            if node.category == category
        )
        lines.append(f"| {category.title()} | {links} |")
    lines.extend(
        [
            "",
            "## All Parts",
            "",
            "| Part | Status | Purpose |",
            "| --- | --- | --- |",
        ]
    )
    for node in atlas.nodes:
        lines.append(
            f"| [{node.title}](../../{node.path}/README.md) | `{node.status}` | {node.purpose} |"
        )
    lines.extend(
        [
            "",
            "## Dependencies",
            "",
            "| Subsystem | Depends on | Used by |",
            "| --- | --- | --- |",
        ]
    )
    for node in atlas.nodes:
        depends_on = ", ".join(atlas.by_id[item].title for item in node.depends_on) or "None"
        used_by = ", ".join(atlas.by_id[item].title for item in atlas.used_by[node.id]) or "None"
        lines.append(f"| [{node.title}](../../{node.path}/README.md) | {depends_on} | {used_by} |")
    lines.extend(
        [
            "",
            "Each linked folder README lists what that part owns, its key files, its limitations, and the checks to run. When ownership changes, update `architecture/repository-atlas.json` and run `./hfx generate`.",
        ]
    )
    return "\n".join(lines) + "\n"
