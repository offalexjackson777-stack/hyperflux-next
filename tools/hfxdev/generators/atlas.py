def collection_readme(atlas: RepositoryAtlas, path: str) -> str:
    children = tuple(node for node in atlas.nodes if node.path.startswith(path + "/"))
    owners: dict[str, tuple[int, int]] = {}
    for node in atlas.nodes:
        canonical = sum(item.startswith(path + "/") for item in node.canonical_files)
        generated = sum(
            item.startswith(path + "/") and item != f"{path}/README.md"
            for item in node.generated_files
        )
        if canonical or generated:
            owners[node.id] = (canonical, generated)
    if path == "LICENSES" and "governance" not in owners:
        owners["governance"] = (1, 0)

    lines = [
        f"# {COLLECTION_TITLES.get(path, path.title())}",
        "",
        GENERATED_NOTICE,
        "",
        COLLECTION_PURPOSES.get(
            path,
            "This collection groups related repository authorities and generated outputs.",
        ),
        "",
    ]
    if children:
        lines.extend(
            [
                "## Subsystems",
                "",
                "| Area | Purpose |",
                "| --- | --- |",
            ]
        )
        for node in children:
            lines.append(
                f"| {_link(path, node.path + '/README.md', node.title)} | {node.purpose} |"
            )
        lines.append("")
    if owners:
        lines.extend(
            [
                "## Authorities",
                "",
                "| Owner | Canonical inputs | Generated outputs |",
                "| --- | ---: | ---: |",
            ]
        )
        for identifier, (canonical, generated) in sorted(owners.items()):
            node = atlas.by_id[identifier]
            lines.append(
                f"| {_link(path, node.path + '/README.md', node.title)} | {canonical} | {generated} |"
            )
        lines.append("")
    lines.extend(
        [
            "## Change Workflow",
            "",
            "1. Open the owning subsystem above.",
            "2. Change its declared canonical source, not a generated projection.",
            "3. Run `./hfx generate` from the repository root.",
            "4. Run the verification named by that subsystem.",
        ]
    )
    return "\n".join(lines) + "\n"


def markdown(atlas: RepositoryAtlas) -> str:
    categories = sorted({node.category for node in atlas.nodes})
    lines = [
        "# Repository Atlas",
        "",
        GENERATED_NOTICE,
        "",
        "Maintainer reference for repository ownership. It lists every subsystem with its status, purpose, and dependencies. To learn the system, start with the [architecture overview](../developer/architecture.md) instead.",
        "",
        "File-level contracts live in [`architecture/repository-atlas.json`](../../architecture/repository-atlas.json).",
        "",
        f"- **Subsystems:** {len(atlas.nodes)}",
        f"- **Categories:** {len(categories)}",
        f"- **Publication state:** `{atlas.publication_state}`",
        "",
        "## Browse By Area",
        "",
        "| Area | Subsystems |",
        "| --- | --- |",
    ]
    for category in categories:
        links = ", ".join(
            f"[{node.title}](../../{node.path}/README.md)"
            for node in atlas.nodes
            if node.category == category
        )
        lines.append(f"| {category.title()} | {links} |")
    lines.extend(
        [
            "",
            "## Subsystem Index",
            "",
            "| Subsystem | Status | Purpose |",
            "| --- | --- | --- |",
        ]
    )
    for node in atlas.nodes:
        lines.append(
            f"| [{node.title}](../../{node.path}/README.md) | `{node.status}` | {node.purpose} |"
        )
    lines.extend(
        [
            "",
            "## Dependencies",
            "",
            "| Subsystem | Depends on | Used by |",
            "| --- | --- | --- |",
        ]
    )
    for node in atlas.nodes:
        depends_on = ", ".join(atlas.by_id[item].title for item in node.depends_on) or "None"
        used_by = ", ".join(atlas.by_id[item].title for item in atlas.used_by[node.id]) or "None"
        lines.append(f"| [{node.title}](../../{node.path}/README.md) | {depends_on} | {used_by} |")
    lines.extend(
        [
            "",
            "Each linked folder README names the subsystem's boundaries, key files, limitations, and verification. Update the JSON authority and run `./hfx generate` when ownership changes.",
        ]
    )
    return "\n".join(lines) + "\n"
