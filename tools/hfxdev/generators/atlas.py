from __future__ import annotations

import posixpath
from collections.abc import Mapping

from ..atlas import AtlasNode, RepositoryAtlas


GENERATED_NOTICE = "> Generated by `./hfx generate` from `architecture/repository-atlas.json`. Do not edit manually."


def _link(from_directory: str, target: str, label: str | None = None) -> str:
    relative = posixpath.relpath(target, from_directory)
    return f"[{label or target}]({relative})"


def _bullets(values: tuple[str, ...]) -> list[str]:
    return [f"- {value}" for value in values] or ["- None."]


def _file_bullets(
    from_directory: str,
    values: tuple[str, ...],
    *,
    entries_per_line: int = 1,
) -> list[str]:
    links = [_link(from_directory, value, f"`{value}`") for value in values]
    return [
        "- " + "; ".join(links[index : index + entries_per_line])
        for index in range(0, len(links), entries_per_line)
    ] or ["- None."]


def _node_links(
    atlas: RepositoryAtlas,
    from_directory: str,
    node_ids: tuple[str, ...],
) -> list[str]:
    by_id = atlas.by_id
    return [
        f"- {_link(from_directory, by_id[item].path + '/README.md', by_id[item].title)}"
        for item in node_ids
    ] or ["- None."]


ATLAS_PAGE = "docs/generated/repository-atlas.md"


def _doc_bullets(
    from_directory: str,
    values: tuple[str, ...],
    titles: Mapping[str, str],
) -> list[str]:
    return [
        f"- {_link(from_directory, value, titles[value])}"
        if value in titles
        else f"- {_link(from_directory, value, f'`{value}`')}"
        for value in values
    ] or ["- None."]


def folder_readme(
    atlas: RepositoryAtlas,
    node: AtlasNode,
    titles: Mapping[str, str] | None = None,
) -> str:
    titles = titles or {}
    verification = " ".join(f"`{item}`" for item in node.verification)
    lines = [
        f"# {node.title}",
        "",
        GENERATED_NOTICE,
        "",
        node.purpose,
        "",
    ]
    if node.id == "documentation":
        lines.extend(
            [
                "## Browse By Need",
                "",
                "| Need | Document |",
                "| --- | --- |",
                "| Documentation hub | [Choose a guide](README.md) |",
                "| Installation | [Install and activate safely](user/installation.md) |",
                "| Troubleshooting | [Safe diagnostic steps](user/troubleshooting.md) |",
                "| Privacy | [Local data boundaries](user/privacy.md) |",
                "| Architecture | [System design](developer/architecture.md) |",
                "| Hardware | [Capability boundary](user/hardware.md) |",
                "| Applications | [Stock application ownership](user/applications.md) |",
                "| Readiness | [Release status](project/release-status.md) |",
                "",
            ]
        )
    else:
        guides = tuple(item for item in node.related_docs if "/decisions/" not in item)
        decisions = tuple(item for item in node.related_docs if "/decisions/" in item)
        lines.extend(["## Start Here", "", *_doc_bullets(node.path, guides, titles), ""])
        if decisions:
            lines.extend(
                ["## Decision Records", "", *_doc_bullets(node.path, decisions, titles), ""]
            )
    if node.id == "device-qualification-console":
        lines.extend(
            [
                "## Preview The Source Console",
                "",
                "```sh",
                "python3 tests/qualification_console_fixture_server.py --port 47821",
                "```",
                "",
                "Run this from the repository root and open the local address it prints. It only previews the interface with sample data: it does not read your installed HyperFlux or test hardware. The installed, read-only report of the same view is `hyperfluxctl qualification`.",
                "",
            ]
        )
    if node.limitations:
        lines.extend(["## Limitations", "", *_bullets(node.limitations), ""])
    lines.extend(
        [
        "## Boundaries",
        "",
        "**Owns**",
        "",
        *_bullets(node.owns),
        "",
        "**Does not own**",
        "",
        *_bullets(node.must_not_own),
        "",
        "## Key Files",
        "",
        *_file_bullets(
            node.path,
            node.canonical_files,
            entries_per_line=2 if len(node.canonical_files) > 20 else 1,
        ),
        "",
        "## Verify",
        "",
        f"Run {verification} after changing this area, and run `./hfx generate`"
        f" to refresh its {len(node.generated_files)} generated file(s).",
        "",
        "Maintainers can find the areas this one depends on and the areas that"
        f" use it in the {_link(node.path, ATLAS_PAGE, 'Repository Atlas')}.",
        ]
    )
    return "\n".join(lines) + "\n"


