def _upload(
    governance: GitHubGovernance,
    *,
    name: str,
    path: str,
    retention_days: int,
    if_no_files_found: str = "error",
) -> dict[str, Any]:
    return {
        "name": f"Upload {name}",
        "if": "${{ always() }}",
        "uses": governance.actions_by_id["upload-artifact"].uses,
        "with": {
            "name": name,
            "path": path,
            "if-no-files-found": if_no_files_found,
            "retention-days": retention_days,
        },
    }


def _verification_summary(output: str) -> dict[str, Any]:
    return {
        "name": "Publish bounded verification summary",
        "if": "${{ always() }}",
        "env": {"HFX_SOURCE_REVISION": EXACT_SOURCE_REVISION},
        "run": (
            f'./hfx ci summary --result {output}/result.json '
            '--output "$GITHUB_STEP_SUMMARY" --source-revision "$HFX_SOURCE_REVISION"'
        ),
    }


