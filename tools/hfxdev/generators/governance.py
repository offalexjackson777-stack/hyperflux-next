NOTICE = "# Generated by ./hfx generate. Do not edit manually.\n"
EXACT_SOURCE_REVISION = "${{ github.event.pull_request.head.sha || github.sha }}"


class _ReadableDumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True


def _represent_string(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_ReadableDumper.add_representer(str, _represent_string)


def _yaml(value: dict[str, Any], governance: GitHubGovernance) -> str:
    rendered = yaml.dump(
        value,
        Dumper=_ReadableDumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=False,
        width=1000,
    )
    for action in governance.actions:
        rendered = rendered.replace(
            f"uses: {action.uses}\n",
            f"uses: {action.uses} # {action.version}\n",
        )
    return NOTICE + rendered


def _checkout(governance: GitHubGovernance) -> dict[str, Any]:
    return {
        "name": "Check out exact source",
        "uses": governance.actions_by_id["checkout"].uses,
        "with": {
            "ref": EXACT_SOURCE_REVISION,
            "fetch-depth": 0,
            "persist-credentials": False,
        },
    }


def _caches(governance: GitHubGovernance) -> list[dict[str, Any]]:
    action = governance.actions_by_id["cache"].uses
    return [
        {
            "name": "Restore exact upstream sources",
            "uses": action,
            "with": {
                "path": f"{UPSTREAM_CACHE_PATH}\n",
                "key": "hfx-upstreams-${{ runner.os }}-${{ hashFiles('integrations/catalog.json') }}",
            },
        },
        {
            "name": "Restore verified build caches",
            "uses": action,
            "with": {
                "path": f"{CARGO_CACHE_PATH}\ntarget\n",
                "key": "hfx-build-${{ runner.os }}-${{ hashFiles('Cargo.lock', 'toolchains/development-environment.json') }}",
                "restore-keys": "hfx-build-${{ runner.os }}-\n",
            },
        },
    ]


