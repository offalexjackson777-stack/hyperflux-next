def dependabot(governance: GitHubGovernance, toolchain_packages: tuple[str, ...] = ()) -> str:
    schedule = {"interval": "weekly", "day": governance.dependency_update_day}
    value = {
        "version": 2,
        "updates": [
            {
                "package-ecosystem": "github-actions",
                "directory": "/",
                "schedule": schedule,
                "open-pull-requests-limit": 5,
                "groups": {"github-actions": {"patterns": ["*"]}},
                "labels": ["area: security"],
            },
            {
                "package-ecosystem": "cargo",
                "directory": "/",
                "schedule": schedule,
                "open-pull-requests-limit": 5,
                "groups": {"rust-dependencies": {"patterns": ["*"]}},
                "labels": ["area: security"],
            },
            *[
                {
                    "package-ecosystem": "pip",
                    "directory": directory,
                    "schedule": schedule,
                    "open-pull-requests-limit": 3,
                    "groups": {"python-dependencies": {"patterns": ["*"]}},
                    "labels": ["area: integration", "area: security"],
                    **(
                        {"ignore": [{"dependency-name": name} for name in toolchain_packages]}
                        if toolchain_packages
                        else {}
                    ),
                }
                for directory in ("/sdk/python",)
            ],
        ],
    }
    return _yaml(value, governance)


def codeowners(governance: GitHubGovernance) -> str:
    lines = [NOTICE.rstrip(), "", f"* {' '.join(governance.default_owners)}"]
    for rule in governance.ownership_rules:
        lines.extend(f"{path} {' '.join(rule.owners)}" for path in rule.paths)
    return "\n".join(lines) + "\n"


