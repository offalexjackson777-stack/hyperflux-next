FULL_COMPONENT_CAPABILITIES = (
    "openrazer-native-route",
    "openrgb-plugin",
)


def full_component_descriptor(runtime: LinuxRuntime, *, openrgb_plugin: bool = True) -> str:
    """The installed Full descriptor. A distribution whose OpenRGB cannot load
    the plugin ships Full without it and names only the native route."""

    capabilities = FULL_COMPONENT_CAPABILITIES if openrgb_plugin else FULL_COMPONENT_CAPABILITIES[:1]
    value = {
        "$schema": "https://hyperflux.dev/schemas/distribution-component-descriptor-v1.json",
        "schema": "hyperflux-distribution-component-v1",
        "component_id": "full",
        "product_version": runtime.product.version,
        "capabilities": list(capabilities),
    }
    return json.dumps(value, indent=2, sort_keys=False, ensure_ascii=True) + "\n"


def compiled_plan(manifest: InstallManifest, runtime: LinuxRuntime) -> str:
    value = {
        "schema": "hyperflux-compiled-install-plan-v2",
        "install_manifest_sha256": manifest.source_sha256,
        "product": {
            "name": runtime.product.package_name,
            "version": runtime.product.version,
            "release": runtime.product.package_release,
        },
        "policy": {
            "hardware_writes_on_install": manifest.policy.hardware_writes_on_install,
            "start_service_on_install": manifest.policy.start_service_on_install,
            "enable_service_on_install": manifest.policy.enable_service_on_install,
            "preserve_configuration": manifest.policy.preserve_configuration,
        },
        "builds": [
            {
                "id": build.id,
                "distribution_component": build.distribution_component,
                "kind": build.kind,
                "required": build.required,
                **({"source": build.source} if build.source is not None else {}),
                **({"package": build.package} if build.package is not None else {}),
                **({"target": build.target} if build.target is not None else {}),
                **(
                    {"profile": build.cargo_profile}
                    if build.cargo_profile is not None
                    else {}
                ),
                **({"output": build.output} if build.output is not None else {}),
                **(
                    {"transform": build.transform}
                    if build.transform is not None
                    else {}
                ),
                **(
                    {"destination": build.destination}
                    if build.destination is not None
                    else {}
                ),
                **({"mode": f"{build.mode:04o}"} if build.mode is not None else {}),
                **(
                    {"capability": build.capability}
                    if build.capability is not None
                    else {}
                ),
            }
            for build in manifest.builds
        ],
        "payloads": [
            {
                "component": file.component,
                "distribution_component": file.distribution_component,
                "source": file.source.relative_to(manifest.root).as_posix(),
                "destination": str(file.destination),
                "mode": f"{file.mode:04o}",
                "preserve": file.preserve,
            }
            for file in manifest.files
        ],
    }
    return json.dumps(value, indent=2, sort_keys=False, ensure_ascii=True) + "\n"



def _relations(values: tuple[str, ...]) -> str:
    return " and ".join(f"`{value}`" for value in values)

def markdown(
    manifest: InstallManifest,
    runtime: LinuxRuntime,
    openrazer: OpenRazerNativeDeployment,
    split: ArchSplit,
) -> str:
    receiver = split.output("receiver-dkms").package_name
    driver_owner = next(
        output
        for output in split.outputs
        if openrazer.driver.source_directory in output.tree_destinations
    )
    full = split.edition_output("full").package_name
    required = sum(1 for build in manifest.builds if build.required)
    optional = len(manifest.builds) - required
    preserved = [file for file in manifest.files if file.preserve]
    lines = [
        "# Package Installation",
        "",
        "> Generated by `./hfx generate`. Do not edit manually.",
        "",
        "This page lists what the HyperFlux packages install, what they leave alone, "
        "and how to turn HyperFlux on or roll it back, for packagers and for anyone "
        "who wants to know what an install changes on their system.",
        "",
        f"Install manifest digest: `{manifest.source_sha256}`.",
        "",
        f"Packages at `{runtime.product.version}` release "
        f"`{runtime.product.package_release}`: Core is `{runtime.product.package_name}` "
        f"(background service, SDK, and `hyperfluxctl`) with `{receiver}` (receiver "
        f"driver sources). Full adds `{driver_owner.package_name}` (patched OpenRazer "
        f"driver sources) and `{full}` (the OpenRazer and OpenRGB connections).",
        "",
        "## What Installing Does And Does Not Do",
        "",
        "| Action | What the package does |",
        "| --- | --- |",
        "| Writes to your devices during installation | Never |",
        "| Starts the background service during installation | No |",
        "| Enables the background service during installation | No |",
        "| First run | You enable it without starting it, then reboot normally |",
        "| Your existing configuration | Kept |",
        "",
        "Each package's install hooks only create that package's own system users and "
        "folders and reload systemd and udev. They do not start services, look at "
        "hardware, or turn HyperFlux on.",
        "",
        "## What Gets Built",
        "",
        f"The build plan contains `{required}` required and `{optional}` optional build products.",
        "",
        "| Build | Distribution component | Kind | Required | Destination |",
        "| --- | --- | --- | --- | --- |",
    ]
    for build in manifest.builds:
        output = build.destination or "-"
        lines.append(
            f"| `{build.id}` | `{build.distribution_component}` | `{build.kind}` | "
            f"{'yes' if build.required else 'no'} | `{output}` |"
        )
    lines.extend(
        [
            "",
            "## Installed Files",
            "",
            f"The packages install `{len(manifest.files)}` files. "
            "Every file goes under `/etc` or `/usr`, and no two files share a path.",
            "",
            "| Payload | Distribution component | Files | Preserved destination |",
            "| --- | --- | ---: | --- |",
        ]
    )
    for payload in manifest.payloads:
        files = [file for file in manifest.files if file.component == payload.id]
        preserve = payload.destination if payload.preserve else "-"
        lines.append(
            f"| `{payload.id}` | `{payload.distribution_component}` | "
            f"{len(files)} | `{preserve}` |"
        )
    lines.extend(["", "## Your Configuration", ""])
    if preserved:
        lines.extend(
            f"- `{file.destination}` is kept when you upgrade or reinstall." for file in preserved
        )
    else:
        lines.append("No mutable configuration was declared, which is an invalid release state.")
    lines.extend(
        [
            "",
            "## OpenRazer Driver And Updates",
            "",
            f"`{driver_owner.package_name}` owns the source-bound patched driver at "
            f"`{openrazer.driver.source_directory}`. It provides "
            f"{_relations(driver_owner.provides)} and conflicts with "
            f"{_relations(driver_owner.conflicts)}, so a system update cannot install a "
            "second owner over the transformed source tree.",
            "",
            f"Official OpenRazer `{openrazer.compatibility.verified_upstream_version}` "
            "daemon and Python-client packaging may receive distribution release-suffix "
            "updates. Runtime readiness is checked with the transformed module capability "
            f"`{openrazer.compatibility.runtime_capability.modinfo_field}="
            f"{openrazer.compatibility.runtime_capability.expected_value}`, not a package "
            "release string. A different upstream source version fails closed and keeps "
            f"`{openrazer.relay.service_unit}` stopped until HyperFlux is rebased and "
            "reverified.",
            "",
            "## Turning It On And Rolling Back",
            "",
            "Installation leaves every HyperFlux service disabled and inactive. Keep the "
            "receiver connected, enable the units without starting them, and reboot:",
            "",
            "```sh",
            manifest.first_run_activation.enable_command(runtime),
            manifest.first_run_activation.activation_command(),
            "```",
            "",
            "After login, run the read-only `hyperfluxctl doctor`; the read-only "
            "`hyperfluxctl qualification --json` report is what a hardware report asks for. "
            "Live activation without a "
            "reboot requires disconnecting the receiver, so use "
            f"`{manifest.first_run_activation.disconnected_command(runtime)}` only when "
            "another keyboard, mouse, or verified SSH session can recover the machine.",
            "",
            "Rollback uses a complete prior source-bound Core/Full pair through the package "
            "manager. Do not copy files into `/usr/src`, overwrite DKMS trees, or mix an "
            "upstream OpenRazer driver package with the HyperFlux-owned transform. Existing "
            "configuration remains preserved across supported package transitions.",
            "",
            "The Arch package base consumes independently staged `linux` and payload-bearing "
            "`full` components. Ubuntu 26.10 and Debian 14 `.deb` packages and Fedora 44 "
            "and openSUSE Tumbleweed `.rpm` packages of both editions are built and "
            "checked in CI every week but not published yet.",
            "",
        ]
    )
    return "\n".join(lines)
